// ---------------------------------------------------------------------------
// 冷却剩余时间换算 (纯函数, 放在共享头里 ⇒ **离线可单测**, 见 recttest.cpp)
//
//   输入就是游戏里那两个 int (单位 = tick, 1 tick = 1/100 秒):
//     remain = refresh_time - refresh_counter  ⇒ 剩余 tick
//     tick -> 十分之一秒 的换算系数 = 100/1000 = **1/10**
//   屏幕只画得下 4 个字符 (两位整数 + 小数点 + 一位小数), 而游戏里正常冷却最长 50 秒
//   (5000 tick) ⇒ 连一位数都用不满; 但挑战/传送带/改过的冷却可能给出更离谱的值 ——
//   真遇到时**不要**直接截断成 99.9 (那样数字会卡住不动, 比不显示更误导), 而是**按比例压缩**:
//   分子分母都按"99.9 秒为满格"缩放 ⇒ 数字仍单调递减、仍能一眼看出哪张先好。
//
//   返回值 = 剩余时间的**十分之一秒** (0..999); 0 = 已经就绪/数据无效(不显示)。
//   ★★ 全部用 32 位整数运算 (硬规矩) ★★
//     这个头会被**注入 DLL** 一起编译, 而 DLL 是 `-nostdlib` 链接的: 一旦出现
//     64 位除法 (`long long` / `long long`), GCC 就会去调 libgcc 的 `__divdi3`,
//     链接期直接 `undefined reference to '__divdi3'` (2026-10-12 实测踩到)。
//     所以超长冷却的按比例压缩改成"先缩放分母, 再用商+余数四舍五入" —— 结果与
//     `remain * 999 / refresh_time` 四舍五入等价, 但没有任何溢出/64 位运算。
// ---------------------------------------------------------------------------
constexpr int kCooldownTicksPerTenth = kGameTicksPerSecond / 10;         // 10 tick = 0.1 秒
constexpr int kCooldownMaxTicks = kCooldownMaxTenths * kCooldownTicksPerTenth; // 9990 tick = 99.9 秒

constexpr int CooldownTenths(int refresh_counter, int refresh_time)
{
    if (refresh_time <= 0 || refresh_counter < 0)
        return 0;
    if (refresh_counter >= refresh_time)
        return 0; // 冷却已满 = 就绪, 不显示
    const int remain = refresh_time - refresh_counter; // 剩余 tick (> 0)
    if (refresh_time <= kCooldownMaxTicks)
    {
        const int t = remain / kCooldownTicksPerTenth; // 常态: 10 tick = 0.1 秒
        return (t >= 1) ? t : 1; // ★ 还剩不到 0.1 秒也要显示 0.1 —— 显示 "0.0" 会让人以为已就绪
    }
    // 超长冷却: 等比压缩到 99.9 秒满格 (四舍五入到十分位; remain>0 ⇒ 结果 >= 1)
    //   scaled = refresh_time / 999 (>10, 因为这里 refresh_time > 9990)
    //   t = remain / scaled, 余数 >= scaled/2 就进一位   ← 等价于四舍五入, 且全程 32 位
    const int scaled = refresh_time / kCooldownMaxTenths;
    if (scaled < 1)
        return kCooldownMaxTenths; // 理论上到不了这里 (refresh_time > 9990)
    const int q = remain / scaled;
    const int r = remain % scaled;
    int t = q + ((r * 2 >= scaled) ? 1 : 0);
    if (t <= 0)
        return 1; // 还在冷却就至少显示 0.1, 别显示成 0.0
    return (t > kCooldownMaxTenths) ? kCooldownMaxTenths : t;
}

