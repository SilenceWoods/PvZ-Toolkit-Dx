// ---------------------------------------------------------------------------
constexpr int32_t kStrOffBuf = 0x04;    // `_Bx`: `_Buf[16]` 或 `char* _Ptr`
                                        //   证据 (a) 0x477A6E / (b) 0x519553 / (c) 0x58DFA4
constexpr int32_t kStrOffSize = 0x14;   // `_Mysize`
                                        //   证据 (a) 0x477A6B / (b) 0x519538 / (c) 0x58DF78
constexpr int32_t kStrOffRes = 0x18;    // `_Myres` (容量)
                                        //   证据 (a) 0x477A64 / (b) 0x519548 / (c) 0x58DF99
constexpr int32_t kStrCapBuf = 0x10;    // `_BUF_SIZE` = 16 (阈值本身, 见 (b)(c)(d))
constexpr int32_t kStrSSOMax = kStrCapBuf - 1; // 默认容量 15 (证据 (a))
constexpr int32_t kStrSize = 0x1C;      // sizeof(SexyString) = 28 (证据 (a) 的栈帧)
static_assert(kStrSize == kStrOffBuf + kStrCapBuf + 8, "布局必须自洽: _Bx(16) + size + res");
static_assert(kStrSSOMax < kStrCapBuf, "SSO 容量必须严格小于 _BUF_SIZE");
static_assert(kStrOffRes == kStrOffSize + 4, "_Mysize/_Myres 必须相邻");

// "栈上的 SexyString": 固定 0x1C 字节、4 字节对齐 —— 与游戏里的对象**同尺寸同对齐**。
//   ★ 为什么自己做而不 include <string>: 本 DLL 是 `-nostdlib` 的 GCC 产物, 它的
//     `std::string` 布局与 VC8 的**完全不是一回事**; 拿错布局传给游戏 = 立刻崩。
struct CdSsoString
{
    alignas(4) unsigned char raw[kStrSize];
};
static_assert(sizeof(CdSsoString) == kStrSize, "CdSsoString 必须与 SexyString 同尺寸");

// 把 `s[0..n)` 按 VC8 `std::string` 的 **SSO** 形态写进调用方给的内存。
//   返回 false ⇒ **串太长 (需要堆)**: 调用方**必须放弃**这个对象, 绝不退化成"自己 malloc"。
//   ★ 为什么把 `_Myres` 写成 15: 那就是默认构造出来的容量, 且 `15 < 16` ⇒
//     游戏自己的析构 (判据 `_Myres >= 0x10` 才 free) **什么都不做** ⇒ 零堆分配、零释放。
//   ★ `_Alval` (B+0x00) 置 0: SSO 路径下从不被读, 但把它写成确定值可以让
//     "对象里没有未初始化字节" 这条离线断言成立 (recttest 会逐字节比对整块 0x1C)。
constexpr bool CdSsoInit(CdSsoString &obj, const char *s, int32_t n)
{
    if (s == nullptr)
        return false;
    if (n < 0 || n >= kStrCapBuf)
        return false; // >= 16 字节就必须走堆 ⇒ 拒绝 (我们绝不分配)
    unsigned char *b = obj.raw;
    for (int32_t i = 0; i < 4; i++)
        b[i] = 0; // _Alval (不参与 SSO 路径)
    for (int32_t i = 0; i < kStrCapBuf; i++)
        b[kStrOffBuf + i] = 0; // 内部缓冲整体清零 (确定性)
    for (int32_t i = 0; i < n; i++)
        b[kStrOffBuf + i] = static_cast<unsigned char>(s[i]);
    const int32_t size = n;
    const int32_t cap = kStrSSOMax;
    b[kStrOffSize + 0] = static_cast<unsigned char>(size & 0xFF);
    b[kStrOffSize + 1] = static_cast<unsigned char>((size >> 8) & 0xFF);
    b[kStrOffSize + 2] = static_cast<unsigned char>((size >> 16) & 0xFF);
    b[kStrOffSize + 3] = static_cast<unsigned char>((size >> 24) & 0xFF);
    b[kStrOffRes + 0] = static_cast<unsigned char>(cap & 0xFF);
    b[kStrOffRes + 1] = static_cast<unsigned char>((cap >> 8) & 0xFF);
    b[kStrOffRes + 2] = static_cast<unsigned char>((cap >> 16) & 0xFF);
    b[kStrOffRes + 3] = static_cast<unsigned char>((cap >> 24) & 0xFF);
    return true;
}

// `_Mysize` / `_Myres` 的只读视图 (小端; 与 x86 一致)
constexpr int32_t CdSsoSize(const CdSsoString &obj)
{
    const unsigned char *b = obj.raw;
    return static_cast<int32_t>(static_cast<uint32_t>(b[kStrOffSize]) |
                                (static_cast<uint32_t>(b[kStrOffSize + 1]) << 8) |
                                (static_cast<uint32_t>(b[kStrOffSize + 2]) << 16) |
                                (static_cast<uint32_t>(b[kStrOffSize + 3]) << 24));
}

constexpr int32_t CdSsoCap(const CdSsoString &obj)
{
    const unsigned char *b = obj.raw;
    return static_cast<int32_t>(static_cast<uint32_t>(b[kStrOffRes]) |
                                (static_cast<uint32_t>(b[kStrOffRes + 1]) << 8) |
                                (static_cast<uint32_t>(b[kStrOffRes + 2]) << 16) |
                                (static_cast<uint32_t>(b[kStrOffRes + 3]) << 24));
}

// 游戏的内联析构会不会去 free —— **只由 `_Myres` 决定** (证据 (d))。
//   ★ 这是"不需要堆分配、也不需要释放"的唯一判据, 离线单测直接钉住它。
constexpr bool CdSsoNeedsFree(const CdSsoString &obj) { return CdSsoCap(obj) >= kStrCapBuf; }

// `c_str()` 会返回哪个指针 —— 复刻 VC8 的分支 (证据 (b)(c)):
//   容量 < 16 ⇒ 对象自己 `+0x04` 那个内部缓冲; 否则 ⇒ `+0x04` 里存的堆指针。
//   ★ 我们构造出来的对象**永远**落第一条分支 (容量 = 15)。
constexpr const char *CdSsoCStr(const CdSsoString &obj)
{
    if (CdSsoCap(obj) < kStrCapBuf)
        return reinterpret_cast<const char *>(obj.raw + kStrOffBuf);
    const unsigned char *p = obj.raw + kStrOffBuf;
    const uint32_t addr = static_cast<uint32_t>(p[0]) | (static_cast<uint32_t>(p[1]) << 8) |
                          (static_cast<uint32_t>(p[2]) << 16) | (static_cast<uint32_t>(p[3]) << 24);
    return reinterpret_cast<const char *>(static_cast<uintptr_t>(addr));
}

