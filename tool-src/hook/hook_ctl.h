// 模式 (三选一; 由工具界面/环境变量决定, 每帧原样下发)
enum CdDrawMode : uint32_t
{
    CDMODE_OFF = 0,    // 关闭 (cd_on 也写 0)
    CDMODE_RECT = 1,   // 矩形 (老方式; 也是**默认**与**自动回退**目标)
    CDMODE_NATIVE = 2, // 游戏字体 (新方式)
    CDMODE_LAST = CDMODE_NATIVE,
};

// 模式值是否合法。★ "模式未知 ⇒ 走矩形路径" 这条硬规矩就靠它。
constexpr bool CdModeValid(uint32_t mode) { return mode <= CDMODE_LAST; }

// ---- 模式文本解析 (纯函数: 工具侧解析与离线单测**同一份实现**) ----
//   只认 `0` / `1` / `2`, 允许**首尾空白** (getenv 的常见形态); 其余一律返回 fallback。
//   ★ 为什么严格: `PZTK_CD_MODE=22` / `0x1` / 空串都**不能**被当成合法模式 ——
//     否则"模式未知"这条闸门就永远触发不了, 也就没人知道配置写错了。
constexpr bool CdModeIsSpace(char c) { return c == ' ' || c == '\t' || c == '\r' || c == '\n'; }

constexpr int32_t CdParseModeText(const char *s, int32_t n, int32_t fallback)
{
    if (s == nullptr || n <= 0)
        return fallback;
    int32_t i = 0;
    int32_t j = n;
    while (i < j && CdModeIsSpace(s[i]))
        i++;
    while (j > i && CdModeIsSpace(s[j - 1]))
        j--;
    if (j - i != 1)
        return fallback;
    const char c = s[i];
    if (c < '0' || c > '2')
        return fallback;
    return static_cast<int32_t>(c - '0');
}

