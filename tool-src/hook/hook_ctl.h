// ★★ 卡面矩形: **照抄游戏自己的算式** (硬规矩, 别再自己推坐标系) ★★
//
//   游戏的绘制链 (game-src 逐行对照, 这是唯一权威):
//     Board::DrawUIBottom   : if (mSeedBank->BeginDraw(g)) { mSeedBank->Draw(g); ... }
