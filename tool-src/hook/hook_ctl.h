// ---------------------------------------------------------------------------
// ★★ v38: 原生路径的"重试判据"与"缓存判据" —— **任何一帧失败都不许影响下一帧** ★★
//
//   用户实机反馈里有一条硬方向: "不许一次性闩锁卡死 / 不许粘滞状态"。字号自检这条路上
//   v37 有两个**会粘住**的地方, 这里把它们做成共享头纯函数, 由离线单测逐条钉住:
//     ① 槽地址不可读时 v37 把 `g_font_slot_readable = false` **缓存住了**, 而它只在
//        "工具下发的地址变了"时才重算 ⇒ 只要那一次读失败 (页面还没提交 / 工具刚下发),
//        这一局就**永远**用不上原生方式 —— 哪怕下一帧页面已经可读。
//        ⇒ `CdFontSlotProbeDue`: **只要上一次没读成功, 下一帧就必须重试**。
//     ② 自检失败过的字体指针 v37 "不重复查" —— 这一条**必须保留** (否则每帧都做几次
//        VirtualQuery, 而且查的还是同一个坏对象), 但**换了一个新的 `_Font*` 之后必须
//        重查** (游戏换关/重载资源会换对象)。v37 的写法凑巧也对, 现在把它写成判据,
//        免得以后有人"优化"成"永久禁用原生方式"。
// ---------------------------------------------------------------------------
// 这一帧要不要重新探测"字体全局槽可读"?
//   slot_addr_changed = 工具下发的槽地址与上一次核对过的不一样
//   last_readable     = 上一次探测的结果 (true = 上一次读成功)
constexpr bool CdFontSlotProbeDue(bool slot_addr_changed, bool last_readable)
{
    return slot_addr_changed || !last_readable;
}

// 这一帧要不要重跑**全套字体自检**?
//   slot_pub / slot_cached = 工具下发的槽地址 / 上一次核对过的槽地址
//   font_ptr               = 本帧现读到的 `_Font*` (0 = 游戏还没把字体塞进槽)
//   font_cached            = 上一帧自检通过并缓存下来的 `_Font*`
//   font_bad_ptr           = 上一次**自检失败**的那个 `_Font*`
//   ★ 关键一条: 即使 `font_bad_ptr != 0` (上一个对象是坏的), 只要 **font_ptr 换成了
//     一个新值** 就必须重查 ⇒ "失败"绝不粘滞到下一个对象。
constexpr bool CdFontSelfCheckNeeded(uint32_t slot_pub, uint32_t slot_cached, uint32_t font_ptr,
                                     uint32_t font_cached, uint32_t font_bad_ptr)
{
    if (slot_pub == 0)
        return false; // 工具没下发地址 ⇒ 没得查
    if (slot_pub != slot_cached)
        return true; // 换了槽地址 ⇒ 一切重来 (含清掉"坏指针"记录)
    if (font_ptr == 0)
        return false; // 槽里还是 0 (字体还没加载) ⇒ 没得查, 也不许记成失败
    if (font_cached != 0 && font_cached == font_ptr)
        return false; // 上一帧已经全套核对过同一个对象 ⇒ 命中缓存
    if (font_bad_ptr == font_ptr)
        return false; // 同一个坏对象不重复查 (省掉每帧的 VirtualQuery)
    return true;      // ★ 新对象 (哪怕上一帧失败过) ⇒ 必须重查
}

// ---------------------------------------------------------------------------
// v37: 原生路径的**放置几何** (纯函数 ⇒ DLL 与离线单测 include 同一份)
//   契约与矩形路径**完全一致**: 只画在"可画区"里 (`CdDigitArea`), 且
//   ① 整块文字必须落在卡面内; ② 绝不与卡上的阳光费用相交; ③ 绝不与阳光计数器相交。
//   区别只在于"这块文字多大" —— 矩形路径是字模画布 (10x14), 原生路径是
//   **游戏字体自己量出来的** (StringWidth x mHeight), 宽度由游戏决定 ⇒ 必须能拒。
//
//   ★★ `kCdNativeMargin` —— 这个 4px 余量是**必须**的, 理由是诚实的 ★★
//     我们传给 `DrawString` 的 `theY` 与"墨迹顶端"的关系是
//         anImageY = theY - (mAscent - layerOffsetY - charOffsetY)
//     (`ImageFont::DrawStringEx`)。`mAscent` 我们能从 `_Font` +0x04 现读并证明,
//     但 `layerOffsetY` / `charOffsetY` 只存在于**打包进 `main.pak` 的字体定义**里,
//     本机拿不到 ⇒ 这几个像素属于【仍属假设】。⇒ 做法是**留余量**:
//       把文字居中在"可画区**四周各内缩 kCdNativeMargin**"的安全区里, 并且把
//       文字框**外扩 kCdNativeMargin** 之后再与两条禁画区判相交。
//     任何一条不过 ⇒ **整帧降级成矩形路径** (宁可换回老方式, 也绝不压阳光/溢出卡面)。
// ---------------------------------------------------------------------------
//   ★★ v41: 这个"安全余量"从 4 改成 **0** —— 因为 v41 的居中对象已经是**实测的墨迹盒**
//     (见上面的 `kFontInk*`), 不需要再给"墨迹可能比文字框多占几像素"留模糊余量了 ★★
//     ① v37..v40 的 4px 是**诚实的猜测**: 那时传给 `DrawString` 的 `theY` 与"墨迹顶端"的
//        关系里, `layerOffsetY`/`charOffsetY` 只存在于 `main.pak` 里 ⇒ 只能留余量兜着;
//     ② v41 把这四个边界**从 pak 量出来了** (逐串复核, 七条串同值) ⇒ 余量改成 0 之后:
//          * 闸门判的**就是**真正会画上去的那块墨迹 (`CdNativePlaceGate` 直接吃墨迹盒),
//            不再靠"外扩 4px 猜";
//          * 50x70 卡面上最宽的 `99.9` 墨迹 = 47 <= 48 (可画区宽) ⇒ 仍然放得下;
//          * 墨迹下沿 = 卡顶 + 44 < 54 (阳光费用区) ⇒ 仍然留 10px。
//     ③ 谁把 `kFontInk*` 改大 (换了字体却忘了重量), 上面那条 `static_assert`
//        与 recttest 的"墨迹盒必须落在可画区里"断言会挡住。
constexpr int32_t kCdNativeMargin = 0;
static_assert(kCdNativeMargin >= 0 && kCdNativeMargin <= 8, "余量必须是个合理的小数");

// ★★ v40: 换了更大的字体之后, 安全区与这个 4px 余量**一个字节都没改** —— 结论是"够用" ★★
//   实测 (数字全部来自出厂 exe + 出厂 main.pak, 见 `kFontGlobalVA` 上面那张表):
//     * 安全区 = `CdDigitArea(card)` (50x70 卡面 ⇒ 48 x 43) 四周各内缩 4 ⇒ **40 x 35**;
//     * `FONT_HOUSEOFTERROR16` 最宽的一条 `99.9` = **34 x 32** ⇒ 宽余 **6px**、高余 **3px**;
//     * 居中落点 (50x70 卡面): `x = 卡左 + 8`、`y = 卡顶 + 15` ⇒ 框 = (8,15)-(41,46);
//       外扩 4px ⇒ (4,11)-(45,50): 仍然整个落在卡面内, 下沿 50 < 54 (阳光费用区上沿) ✓
//     * 相比旧字体 (v37..v39 的 `FONT_CONTINUUMBOLD14`: 39 x 31 ⇒ 框 (5,16)-(43,46)):
//       **墨迹高了 6px (26 -> 32)**, 而框只是从 5..43 变成 8..41 (仍然居中)。
//   ⇒ 两条禁画区判据 (`CdNativePlaceGate` 与阳光费用区 / 阳光计数器) 的**基准没变**,
//     只是"量出来的宽高"变了 ⇒ 居中坐标自动重算 (这正是"换完重算居中与安全区")。
//   ★ 万一某张卡比 50x70 更小 (字放不下) ⇒ `CdNativeTextRect` 返回 false ⇒ 走既有的
//     "跳过并记原因" (`CDNAT_FIT_BAD` → 本帧降级成矩形路径), **绝不缩小字号、绝不溢出卡面**。

constexpr CardRect CdRectGrow(const CardRect &r, int32_t m)
{
    CardRect o = {r.x - m, r.y - m, r.w + 2 * m, r.h + 2 * m};
    return o;
}

constexpr CardRect CdRectShrink(const CardRect &r, int32_t m)
{
    CardRect o = {r.x + m, r.y + m, r.w - 2 * m, r.h - 2 * m};
    return o;
}

constexpr bool CdNativeTextRect(const CardRect &card, int32_t tw, int32_t th, CardRect &out)
{
    out.x = 0;
    out.y = 0;
    out.w = 0;
    out.h = 0;
    const CardRect area = CdDigitArea(card);
    const CardRect safe = CdRectShrink(area, kCdNativeMargin);
    if (CdRectEmpty(area) || CdRectEmpty(safe))
        return false;
    if (tw <= 0 || th <= 0)
        return false;
    if (tw > safe.w || th > safe.h)
        return false; // ✅ 放不下就**不画**这张卡 (绝不缩小字号、绝不溢出卡面)
    out.w = tw;
    out.h = th;
    out.x = safe.x + (safe.w - tw) / 2;
    out.y = safe.y + (safe.h - th) / 2;
    // 居中之后仍然必须整个落在安全区/可画区/卡面里 (奇偶差 1px 时靠这几条钉住)
    return CdRectInside(out, safe) && CdRectInside(out, area) && CdRectInside(out, card);
}

// ★★ v41: "游戏当场量到的步进宽 tw" -> "墨迹盒 + 落点" 的**唯一一份**换算 ★★
//   契约 (与 v37..v40 完全一致, 只是把"居中对象"从步进盒换成墨迹盒):
//     ① 墨迹盒**整个**落在可画区 (`CdDigitArea`) 与卡面里;
//     ② 墨迹盒与**阳光费用区**、**阳光计数器**都不相交 (由 `CdNativePlaceGate` 再判一次);
//     ③ 放不下 (比可画区还宽/还高) ⇒ 返回 false ⇒ 本帧降级成矩形路径 (绝不缩字号、绝不溢出)。
//   输入: card (卡面), tw = 游戏当场 `StringWidth` 量到的步进宽, ascent = 游戏字体的 mAscent。
//   输出: ink = 墨迹盒 (已居中), pen_x = 传给 `DrawString` 的 theX,
//         cell_top = 字形格顶 ⇒ 传给 `DrawString` 的 theY = cell_top + ascent。
//   ★ 为什么 theY 要加 ascent: `ImageFont` 把墨迹画在 `theY - (mAscent - 偏移)` ⇒
//     传 cell_top + ascent 才能让墨迹落在 cell_top + 偏移 上 (v37 起就是这么算的)。
//   ★★ v42: "居中"这一步**一个字节都没改** (仍然是 `CdNativeTextRect`); 校准量的叠加在
//     `CdNativeInkPlaceOffset` 里, 由 `CdNativeInkPlace` 用 `kCdNativeNudgeX/Y` 调它 ★★

// ★★ v42: 居中之后的墨迹盒还能往右(+)/往左(-)、往下(+)/往上(-) 各挪多少 px ★★
//   这是**预算**(不是估计): 用与落点闸门**同源**的判据算出来的闭区间 ——
//     x: [可画带左沿(与卡面左沿取大), 可画带右沿(与卡面右沿取小) - 墨迹宽]
//     y: [可画带上沿(与卡顶取大), 可画带下沿(= 费用区上沿) - kCdNativeNudgeCostGap - 墨迹高]
//   ★ 为什么 x 只用"可画带 + 卡面"而不再内缩 `CdDigitArea` 的那 1px: `kCdPanelPad`(1)
//     是**矩形路径**为字符格子留的内缩量; 原生路径的判据是"墨迹盒本身在卡面/可画带里"
//     (用户硬规矩), 那 1px 就是校准量唯一能用的余量 —— 它**只**放大到可画带, 不越卡面一寸。
constexpr bool CdNativeNudgeRange(const CardRect &card, int32_t ink_w, int32_t ink_h, int32_t cx,
                                  int32_t cy, int32_t &lo_x, int32_t &hi_x, int32_t &lo_y,
                                  int32_t &hi_y)
{
    lo_x = 0;
    hi_x = 0;
    lo_y = 0;
    hi_y = 0;
    if (ink_w <= 0 || ink_h <= 0 || CdRectEmpty(card))
        return false;
    const CardRect band = CdPanelArea(card); // 可画带 = 卡顶 + kCdTitleBandH .. 卡顶 + kCdSunCostTopY
    if (CdRectEmpty(band) || ink_w > band.w || ink_h > band.h)
        return false; // 比可画带还大 ⇒ 与 v41 一样: 这张卡不画 (绝不缩字号/绝不溢出)
    // x: 可画带 ∩ 卡面 的公共落点范围, 再减去墨迹宽
    const int32_t x0 = band.x > card.x ? band.x : card.x;
    int32_t x1 = (band.x + band.w) < (card.x + card.w) ? (band.x + band.w) : (card.x + card.w);
    x1 -= ink_w;
    // y: 上界 = 可画带上沿; 下界 = 费用区上沿 - 空隙 - 墨迹高 (半开区间 ⇒ 正好不压费用区)
    const int32_t y0 = band.y > card.y ? band.y : card.y;
    int32_t y1 = (band.y + band.h) < (card.y + card.h) ? (band.y + band.h) : (card.y + card.h);
    y1 -= kCdNativeNudgeCostGap;
    y1 -= ink_h;
    if (x0 > x1 || y0 > y1)
        return false;
    lo_x = x0 - cx;
    hi_x = x1 - cx;
    lo_y = y0 - cy;
    hi_y = y1 - cy;
    return true;
}

// ★★ v42: 居中 + 叠加**任意**偏移 —— 纯函数, DLL 与离线单测**同一份**实现 ★★
//   契约:
//     ① 居中那一步仍然走 `CdNativeTextRect` (算式与 v41 **一字不差**) ⇒ "居中没被改坏";
//     ② 请求的偏移先**夹**到 `CdNativeNudgeRange` 给出的合法区间 (超出 = 不合法 ⇒ 回退到
//        仍然合法的那个子偏移, **绝不**画出越界的墨迹);
//     ③ 叠加之后**再判一次** (可画带 + 卡面) —— 夹取只是必要条件, 这里才是最终自检;
//     ④ `CdNativePlaceGate` (阳光费用区 / 阳光计数器) 由调用方在拿到 ink 之后再判一次。
constexpr bool CdNativeInkPlaceOffset(const CardRect &card, int32_t tw, int32_t ascent,
                                      int32_t want_x, int32_t want_y, CardRect &ink, int32_t &pen_x,
                                      int32_t &cell_top)
{
    ink = CardRect{0, 0, 0, 0};
    pen_x = 0;
    cell_top = 0;
    if (tw <= 0 || ascent <= 0)
        return false;
    // 墨迹宽 = 步进宽 + 两侧多出来的那点 (描边层比步进盒宽, 见 kFontInk* 的说明)
    const int32_t ink_w = tw + kFontInkOverhangW;
    if (!CdNativeTextRect(card, ink_w, kFontInkH, ink))
        return false; // ★ 居中 + "必须整个在可画区/卡面里"的自检都在里面 (v41 原样)
    int32_t lo_x = 0;
    int32_t hi_x = 0;
    int32_t lo_y = 0;
    int32_t hi_y = 0;
    if (!CdNativeNudgeRange(card, ink_w, kFontInkH, ink.x, ink.y, lo_x, hi_x, lo_y, hi_y))
        return false;
    const int32_t nx = want_x < lo_x ? lo_x : (want_x > hi_x ? hi_x : want_x);
    const int32_t ny = want_y < lo_y ? lo_y : (want_y > hi_y ? hi_y : want_y);
    ink.x += nx;
    ink.y += ny;
    // ★ 叠加之后再判一次: 墨迹盒必须仍然整个落在可画带与卡面里 (否则**不画**这张卡)
    if (!CdRectInside(ink, CdPanelArea(card)) || !CdRectInside(ink, card))
    {
        ink = CardRect{0, 0, 0, 0};
        return false;
    }
    pen_x = ink.x - kFontInkLeft;
    cell_top = ink.y - kFontInkTop;
    // 由上面的构造保证: 墨迹盒 == ink, 而 pen_x/cell_top 只是把 ink 反推回绘制锚点
    return ink.w == ink_w && ink.h == kFontInkH;
}

// 请求的偏移**合不合法** (超出预算 = 不合法) —— 负对照/自检用。
//   ★ 生产路径用的是上面的"夹取 + 回退", 不是这个判据; 这个判据存在的意义是:
//     "把校准量设成向下 +12 这类越界值"必须能被**判出来**(离线断言钉住), 而不是悄悄画出去。
constexpr bool CdNativeNudgeLegal(const CardRect &card, int32_t tw, int32_t ascent, int32_t want_x,
                                  int32_t want_y)
{
    if (tw <= 0 || ascent <= 0)
        return false;
    const int32_t ink_w = tw + kFontInkOverhangW;
    CardRect ink = CardRect{0, 0, 0, 0};
    if (!CdNativeTextRect(card, ink_w, kFontInkH, ink))
        return false;
    int32_t lo_x = 0;
    int32_t hi_x = 0;
    int32_t lo_y = 0;
    int32_t hi_y = 0;
    if (!CdNativeNudgeRange(card, ink_w, kFontInkH, ink.x, ink.y, lo_x, hi_x, lo_y, hi_y))
        return false;
    return want_x >= lo_x && want_x <= hi_x && want_y >= lo_y && want_y <= hi_y;
}

// ★★ v42: 生产入口 = 居中 + 叠加**具名校准量** (`kCdNativeNudgeX` / `kCdNativeNudgeY`) ★★
constexpr bool CdNativeInkPlace(const CardRect &card, int32_t tw, int32_t ascent, CardRect &ink,
                                int32_t &pen_x, int32_t &cell_top)
{
    return CdNativeInkPlaceOffset(card, tw, ascent, kCdNativeNudgeX, kCdNativeNudgeY, ink, pen_x,
                                  cell_top);
}

// 原始文字框的位置闸门: CDSKIP_NONE = 可以画; 否则是跳过原因位 (与 CdPlaceGate 同语义)
constexpr uint32_t CdNativePlaceGate(const CardRect &card, const CardRect &text, int32_t bank_x,
                                     int32_t bank_y)
{
    if (CdRectEmpty(text) || !CdRectInside(text, card))
        return CDSKIP_BIT_PANEL;
    // ★ 连同安全余量一起判: 墨迹可能比"文字框"多占几像素 (见上面 kCdNativeMargin)
    const CardRect pad = CdRectGrow(text, kCdNativeMargin);
    if (CdRectOverlap(pad, CdSunCostRect(card)))
        return CDSKIP_BIT_COST;
    if (CdRectOverlap(pad, CdSunCounterRect(bank_x, bank_y)))
        return CDSKIP_BIT_SUN;
    return CDSKIP_NONE;
}

// ---------------------------------------------------------------------------
// v37: 耗时统计 (纯函数 ⇒ 取值范围的合法性由离线单测钉住)
//   ★★ 为什么不用 64 位整数除法 ★★
//     本 DLL 是 `-nostdlib` 链接的 (没有 libgcc): 源码里只要出现 64 位除法, GCC 就会
//     生成对 `__udivdi3`/`__divdi3` 的调用 ⇒ **链接直接失败** (实测: `undefined
//     reference to '__divdi3'`)。所以这里用"逐位长除法"把 `(delta * 1e6) / freq`
//     整个在 **32 位**里算出来 —— 中间积是 64 位, 但**从不**真的构造它。
// ---------------------------------------------------------------------------
constexpr int32_t kCdUsPerFrameMax = 100000; // 100 ms (一帧绘制耗时的合理性上限)
static_assert(kCdUsPerFrameMax > 0, "上限必须是正数");

// 长除法允许的除数上限。为什么是 2^30: 每一步是 `r2 = 2r + bit` 再与除数比较,
//   而 `r < div` ⇒ 只有 `div <= 2^31` 时 `2r + 1` 才不会溢出 32 位。
//   QPC 频率的真实取值 (10MHz / 3.58MHz / 1MHz …) 都远小于它; 超了就不测 (返回 0),
//   绝不让一个"测不准的数"混进诊断。
constexpr uint32_t kCdMulDivDivMax = 0x40000000u;

// (a * mul) / div  —— 纯 32 位长除法, **不依赖任何运行库**。
//   前置条件 (调用方保证): `div <= kCdMulDivDivMax`, 且商 < 2^32。
//   ★ i386 上**乘法**是内联的 (`mull` 一次给出 64 位积), 只有 **64 位除法**才会变成
//     对 `__udivdi3` 的调用 ⇒ 所以这里自己把积算出来、再逐位长除法。
constexpr uint32_t CdMulDivU32(uint32_t a, uint32_t mul, uint32_t div)
{
    if (div == 0 || div > kCdMulDivDivMax)
        return 0;
    const uint64_t prod = static_cast<uint64_t>(a) * static_cast<uint64_t>(mul);
    const uint32_t hi = static_cast<uint32_t>(prod >> 32);
    const uint32_t lo = static_cast<uint32_t>(prod);
    uint32_t q = 0;
    uint32_t r = 0;
    for (int32_t i = 63; i >= 0; i--)
    {
        const uint32_t bit = (i >= 32) ? ((hi >> (i - 32)) & 1u) : ((lo >> i) & 1u);
        const uint32_t r2 = r + r + bit; // r < div <= 2^30 ⇒ 不会溢出
        if (r2 >= div)
        {
            r = r2 - div;
            if (i < 32)
                q |= (1u << i);
        }
        else
        {
            r = r2;
        }
    }
    return q;
}

// QPC 计数差 -> 微秒 (向下取整), 并**夹到** [0, kCdUsPerFrameMax]。为什么夹:
//   ① 频率读失败 (freq == 0) 或时钟回绕 (delta == 0/异常) 都不能变成负数写进控制块;
//   ② 一帧的绘制耗时**不可能**超过 100ms (超了说明测的根本不是绘制段) ⇒ 记成上限
//      比记一个荒谬的数更有用 (界面一眼看出"这个数不可信")。
//   ★ 只量**我们这一段绘制** (矩形段 / 原生段各自一次), 不量游戏总帧率。
constexpr int32_t CdQpcToUs(uint32_t delta, uint32_t freq)
{
    if (freq == 0 || delta == 0)
        return 0;
    if (delta > 0xFFFFFFFFu / 10u)
        return kCdUsPerFrameMax; // 极端大的差值 (每秒几十亿 tick 也是 100ms 级别以上)
    // us = delta*1e6/freq > kCdUsPerFrameMax  ⟺  delta*10 > freq  (两边都是 32 位乘法)
    if (delta * 10u > freq)
        return kCdUsPerFrameMax;
    // 到这里 delta <= freq/10 ⇒ 商 <= 100000, 必定放得进 32 位
    const uint32_t us = CdMulDivU32(delta, 1000000u, freq);
    if (us > static_cast<uint32_t>(kCdUsPerFrameMax))
        return kCdUsPerFrameMax;
    return static_cast<int32_t>(us);
}

// ---------------------------------------------------------------------------
// v37: 模式连线的健康判定 (与 CdWiringHealth 同一套规矩: 判断只有这一份)
//   工具每帧把模式写进 `cd_mode`, DLL 每帧回读进 `cd_seen_mode` —— 两侧不一致
//   就说明"跨进程这一段断了"或者"游戏里挂的是旧 DLL", 必须在诊断行里看得见。
//   ★ `dll_calls == 0` 时 `cd_seen_mode` 还是初值, 报"不一致"是**误报** (与 v28 同)。
// ---------------------------------------------------------------------------
enum CdModeAnomaly : uint32_t
{
    CDMODE_WIRE_OK = 0,
    CDMODE_WIRE_MISMATCH = 1, // 工具写的模式 ≠ DLL 读到的模式 (且跳板确实在跑)
};

constexpr uint32_t CdModeHealth(uint32_t tool_mode, uint32_t seen_mode, uint32_t dll_calls)
{
    if (dll_calls == 0)
        return CDMODE_WIRE_OK;
    return (tool_mode == seen_mode) ? CDMODE_WIRE_OK : CDMODE_WIRE_MISMATCH;
}

// ===========================================================================
// ★★ v38: DLL 什么时候才可以**卸载自己** —— 判据里**没有心跳新鲜度** ★★
//
//   用户实机反馈 (唯一事实来源): "这个注入有点不稳定, 偶尔会中断, 拖修改器主界面也会中断"。
//   根因 (v37 的代码, 逐行可查): DLL 的监视线程里有一条
//     "`ctl->tool_beat` 连续 `kHeartbeatTimeoutTicks` 没变 ⇒ 认定工具已经关了 ⇒
//      卸钩子 + FreeLibraryAndExitThread"
//   而 `kHeartbeatTimeoutTicks` 的初值是 **0**、只在 `MaybeRefreshRowMask()` 里才被改成
//   2 秒 —— 那个函数**只有开了"帧级首发延迟"且命中了设定植物时才会跑**
//   ⇒ 绝大多数会话里超时值就是 **0 tick**: 监视线程每 20ms 轮询一次, 只要**任何一次**
//   轮询没看到心跳变化, 就立刻把钩子全撤掉并把自己卸载。
//   而**拖动修改器主窗口**时, Windows 的模态移动循环跑在 `DefWindowProc` 里面
//   (= 落在我方 `glfwPollEvents()` 的 **DispatchMessage 内部**), 工具的主循环会整段停住
//   ⇒ 心跳必然停 ⇒ 必然卸载 ⇒ 表现出来就是"一拖就中断"。
//
//   ★★ 硬规矩 (用户拍板) ★★
//     DLL **只依赖"最后一次收到的状态"继续画**, 绝不因为"工具暂时不刷新"就停;
//     唯一允许它卸载自己的两种情形是:
//       ① 工具**明确要求**卸载 (`want_unload` —— 正常退出流程);
//       ② 工具的**进程真的没了** (进程句柄被 signal ⇒ 包括被强杀)。
//     "工具进程还在不在"是**布尔事实**, 不是"新鲜度" ⇒ 拖动 / 失焦 / 最小化 / 单帧卡顿
//     / 停在调试器里 都**不可能**再让它卸载。判据做成纯函数 ⇒ 离线单测能直接钉住
//     ("心跳停 10 万次也不许卸载"这条断言就在 recttest 里)。
// ===========================================================================
enum CdUnloadReason : uint32_t
{
    CDUNLOAD_NONE = 0,      // 继续跑 (工具还活着, 也没要求卸载)
    CDUNLOAD_REQUEST = 1,   // 工具明确要求卸载 (want_unload)
    CDUNLOAD_TOOL_GONE = 2, // 工具进程已经不存在了 (被强杀/崩溃)
};

constexpr uint32_t CdUnloadDecision(bool tool_process_alive, bool want_unload)
{
    if (want_unload)
        return CDUNLOAD_REQUEST;
    if (!tool_process_alive)
        return CDUNLOAD_TOOL_GONE;
    return CDUNLOAD_NONE;
}

// ===========================================================================
// ★★ v38: 一行"中断原因" —— 区分"钩点还在但没画" vs "钩点被撤/未注入" ★★
//
//   用户要的是"能定位": 所以把这几种**互斥**的情形做成一份判据 (中文文案在 pvz.cpp,
//   与 CdWiringHealth 同一套做法 —— 写在本头文件里的中文不会进字形表 ⇒ 界面上是方框)。
//   ★ 顺序 = 从最外层往里查: 注入 -> 模式 -> 钩点地址 -> 补丁 -> 跳板 -> 本帧画了几张。
//     第一个不满足的就是"中断原因"。
//   ★ 参数全部是控制块里的**既有**字段, 不新增任何运行时字段。
//     `injected_ever` 是工具侧自己记的"这个游戏进程里 DLL 曾经报过 hook_ok"
//     (用来把"从未注入"与"曾经注入、现在钩点没了"分开 —— 后者才是真正的断链)。
// ===========================================================================
enum CdInterruptKind : uint32_t
{
    CDINT_OK = 0,           // 一切正常 (钩点在, 本帧也画出来了)
    CDINT_MODE_OFF = 1,     // 用户把冷却显示关掉了 (不算故障)
    CDINT_NOT_INJECTED = 2, // 通道在, 但 DLL 没装上钩子 (未注入 / 装钩失败)
    CDINT_HOOK_GONE = 3,    // ★ 曾经装上过, 现在 hook_ok == 0 ⇒ 钩点被撤 (DLL 已卸载)
    CDINT_NO_CALL_ADDR = 4, // 主钩子活着, 但钩点地址没下发 (工具侧地址自检没过)
    CDINT_HOOK_FAIL = 5,    // 地址下发过, 可补丁打不上 (字节不符 / 写保护 / 回读不符)
    CDINT_HOOK_PENDING = 6, // 地址下发过、补丁还没打上 (正常过渡帧)
    CDINT_NO_CALLS = 7,     // 补丁打上了, 可跳板一次都没跑 (那一帧没走到 DrawUIBottom)
    CDINT_DRAW_ZERO = 8,    // 跳板在跑, 但本帧一张卡都没画 (冷却/闸门/预算 ⇒ 看跳过原因)
};

//   injected_ever = 工具侧记的"本进程里 DLL 报过 hook_ok"
//   hook_ok       = ctl->hook_ok        (DLL 报告"钩子已挂上")
//   hook_calls    = ctl->hook_calls     (主钩子被调用过的总次数)
//   cd_seen_mode  = ctl->cd_seen_mode   (DLL 本帧读到的模式)
//   cd_call_addr  = ctl->cd_call_addr   (本帧下发的钩点地址)
//   cd_hook_ok    = ctl->cd_hook_ok     (冷却钩点补丁已打上 —— ★ 闩锁, 会滞后于地址自检)
//   cd_hook_fail  = ctl->cd_hook_fail   (打补丁失败的原因码)
//   cd_calls      = ctl->cd_calls       (跳板跑过的总帧数)
//   drawn         = ctl->cd_cards_last  (本帧画出来的卡数)
constexpr uint32_t CdInterruptKindOf(bool injected_ever, uint32_t hook_ok, uint32_t hook_calls,
                                     uint32_t cd_seen_mode, uint32_t cd_call_addr,
                                     uint32_t cd_hook_ok, uint32_t cd_hook_fail, uint32_t cd_calls,
                                     uint32_t drawn)
{
    if (hook_ok == 0)
        return (injected_ever || hook_calls > 0) ? CDINT_HOOK_GONE : CDINT_NOT_INJECTED;
    if (cd_seen_mode == CDMODE_OFF)
        return CDINT_MODE_OFF;
    if (cd_call_addr == 0)
        return CDINT_NO_CALL_ADDR;
    if (cd_hook_ok == 0)
        return (cd_hook_fail != 0) ? CDINT_HOOK_FAIL : CDINT_HOOK_PENDING;
    if (cd_calls == 0)
        return CDINT_NO_CALLS;
    if (drawn == 0)
        return CDINT_DRAW_ZERO;
    return CDINT_OK;
}

// ===========================================================================
// ★★ v40: "什么时候去注入 DLL" —— 纯函数 (工具侧调用, 离线单测钉住) ★★
//
//   用户拍板 (唯一事实来源), 原话要点:
//     "**不要区分关卡内外** —— 只要没注入成功就**持续重试, 直到成功**。"
//   (v39 的旧规矩里有两条被**删掉**: ① "关卡内最多只执行一次注入意图";
//    ② "同一次停留在关卡里的多次请求合并成一次" —— 它们都让"关卡内没注进去"变成
//    **永远不再试**, 这正是用户要修掉的。)
//
//   为什么要抽成纯函数: 这段判断原来写在 `frontend\imgui_main.cpp` 的主循环里
//   ("`!HookAlive()` 就每秒重试一次"), 混着 GLFW 时间与界面状态 ⇒ 没法离线断言。
//   现在: 「该不该注入 / 该不该等」全在本节 (零内存读、零全局状态),
//   前端只负责"把 `alive_now` 与"此刻想不想要"传进来、按返回值调 `InjectHookDll()`"。
//
//   ★★ 硬规矩 (用户拍板) ★★
//     ① **未成功 ⇒ 持续重试**: 只要 `alive_now == false`, 每过 `kInjectRetrySec` 就再试一发,
//        **关卡内外完全一致** (没有任何 `in_level` 分支)。不是忙等 —— 每帧只问一次时间门,
//        失败路径本身要等 DLL 报 fail (那一段是阻塞的)。
//     ② **已成功 (同一游戏进程) ⇒ 永不重复装卸**: `alive_now == true` 时永远返回 false。
//        反复 `UnloadHookDll()`+`LoadLibraryW` 就是用户看到的"横跳"。
//     ③ **同一时刻只允许一个尝试在飞**: `InjectHookDll()` 是**同步**的 (远程 `LoadLibraryW`
//        + 最多 3 秒等 `hook_ok`), 而本函数只在**冷却到期那一帧**返回 true ⇒ 冷却窗口内
//        涌进来的多次请求**合并**成一次, 只计进 `merged_requests` 诊断计数。
//   ★ 卸载判据**没有**被改动: 本函数只决定"工具要不要**重新注入**", 与"DLL 什么时候卸载自己"
//     是两件事 —— 后者仍只看 `CdUnloadDecision`(工具进程存活 / 明确要求卸载)。
//     心跳停 (拖窗口) 既不会让 DLL 卸载, 也不会在这里触发重新注入。
//   ★ 本函数与结构体都不改控制块布局 (`Control` 里一个字段都没加) ⇒ 纯工具侧改动;
//     但共享头变了 ⇒ 仍然升版本, exe 与 DLL 一起重编 (见 kVersion 上面那段)。
// ===========================================================================
constexpr double kInjectRetrySec = 0.3; // 重试间隔 (秒) —— 关卡内外一致, 不忙等

enum HookInjectState : uint32_t
{
    HINJ_IDLE = 0,  // 还没开始 (没连上游戏 / 通道没建 / 刚换进程)
    HINJ_ALIVE = 1, // 已经注入成功 —— 什么都不做 (不重复装卸)
    HINJ_RETRY = 2, // 没注入成功, 正在**持续重试** (关卡内外一致)
};

// 浮点比较的余量: `now` 是 GLFW 的秒计数 (可能是个很大的数), 而"到点"是拿
// `now + 间隔` 之类的小数慢慢累加上去的 ⇒ 二进制浮点的舍入会让 `now >= next_try`
// 在某些时刻差一个 ULP 而**少打一发**。取 1 微秒: 足够掩盖累加漂移 (实证: 0.15+0.1
// 这类加法在 double 下差 ~1e-17), 又比任何真实调度抖动小 3 个数量级。
constexpr double kInjectTimeEps = 1e-6;

// 下一次可以注入的时刻 (唯一一处加法; 单测用它 = 钉住"间隔就是 kInjectRetrySec")
constexpr double HookInjectNextTry(double now)
{
    return now + kInjectRetrySec;
}

struct HookInjectPolicy
{
    HookInjectState state = HINJ_IDLE;
    double next_try = 0.0;    // 下一次可以去注入的时刻 (只在 HINJ_RETRY 有意义)
    int retry_count = 0;      // 已经发起的重试次数 (成功清零, 换进程清零)
    int merged_requests = 0;  // 冷却窗口内被**合并掉**的请求数 (只作诊断: "待执行请求")

    // 纯决策: 不改自身状态, 只回答"现在要不要真去注入"。
    //   alive_now = DLL 此刻是否真的在报 hook_ok (= `HookAlive()`)
    //   ★ v40 起**没有** `in_level` 参数 —— 决策与"在不在关卡"彻底无关 (这就是用户要的简化)。
    bool WantInject(bool alive_now, double now) const
    {
        if (alive_now)
            return false; // ② 已经注入 = 永不重复装卸
        if (state == HINJ_IDLE)
            return true;  // IDLE 只可能是"第一次"(前端在连上游戏那一帧直接调 Apply)
        if (state == HINJ_RETRY)
            return now + kInjectTimeEps >= next_try; // ① 到点就再试一次 (关卡内外一致)
        return false; // HINJ_ALIVE: 上面已经拦掉了, 这里是防御性兜底
    }

    // 游戏**换进程** (关掉又重开) 时调用: 记忆归零。
    //   为什么不能直接 `state = HINJ_IDLE`: 刚重开的游戏里 DLL 可能还在 (工具没看到断开帧的
    //   "快速重启"), 那时 IDLE 会在下一帧**立刻**打一发注入 = 平白装卸一次。
    //   所以 IDLE 的含义就是"还没开始" —— 前端在**连上游戏的第一帧**直接调 Apply 即可。
    void Reset()
    {
        state = HINJ_IDLE;
        next_try = 0.0;
        retry_count = 0;
        merged_requests = 0;
    }

    // 状态推进 (前端每帧调一次, 无论是否真去注入)。
    //   返回值 = 要不要**现在**执行真正的注入 (`InjectHookDll()`)。
    //   request = 这一帧是否"想让它注入" (前端传 `!alive_now`); 它**只**用来数"被合并掉的
    //   请求"给诊断行看 —— 决定要不要真注入的永远是**时间门**, 不是它 (否则每帧都会注入)。
    bool Apply(bool alive_now, bool request, double now)
    {
        if (alive_now)
        {
            // ② 已经注入: 什么都不做 (只把记忆归位)
            if (state != HINJ_ALIVE)
            {
                state = HINJ_ALIVE;
                retry_count = 0;
                merged_requests = 0;
            }
            return false;
        }

        if (state == HINJ_IDLE)
        {
            // 第一次: **立刻**试一发 (本函数直接返回 true, 不走下面的时间门 ⇒ 与 now 无关)。
            //   ★ 状态必须一次到位 (HINJ_RETRY): 若这里漏了, 下一帧还是 IDLE, 会**再打一发**
            //     = 装卸两次 (v39 实测踩过; v40 现在没有第二个"待执行"状态了, 更简单)。
            state = HINJ_RETRY;
            next_try = HookInjectNextTry(now);
            retry_count = 1;
            merged_requests = 0;
            return true;
        }

        // ③ 没注入成功 (或曾经成功过又被撤了): 到点就再试一发 —— **关卡内外一致**。
        //   ★ `next_try` 只在**真的发起一次注入**时更新 —— 它记的是"还欠多久才能再试"
        //     (冷却到期时刻), 不是"每次调用都往后推"。若每帧都推, 时间门永远不成立 ⇒
        //     变成每帧都试的忙等 (v39 实测踩过这个坑)。
        //   ★ 只对**单调递增**的 now 有意义 (GLFW 的 glfwGetTime 就是单调的); 传进来的
        //     时刻若倒退 (测试里刻意构造过), 这一段会按"没到点"处理, 不会崩也不会误注入。
        if (state != HINJ_RETRY)
        {
            state = HINJ_RETRY;
            retry_count = 0; // 从"曾经成功过"掉回重试: 计数从这一发重新算
        }
        if (now + kInjectTimeEps >= next_try)
        {
            next_try = HookInjectNextTry(now); // 冷却到期 = 这次真的试过了
            retry_count++;
            return true;
        }
        if (request)
            merged_requests++; // 冷却窗口内又来一个请求 ⇒ 与那一发合并 (不额外注入)
        return false; // 还没到点
    }
};

