//     SeedPacket::Draw      : DrawSeedPacket(g, mOffsetX, 0.0f, ...)  ← 只传 mOffsetX / 0
//   ⇒ 卡面矩形 (在**当时那个 Graphics 的空间**里) =
//        x = SeedBank.mX + packet.mX + packet.mOffsetX
//        y = SeedBank.mY + packet.mY
//        w = packet.mWidth  (构造里 50)   h = packet.mHeight (构造里 70)
//   这个式子与 Board::UpdateToolTip (Board.cpp:3741) 给 ToolTip 用的坐标**逐项相同**
