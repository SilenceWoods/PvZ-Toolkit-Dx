constexpr uint8_t kFntDrawRet[3] = {0xC2, 0x18, 0x00}; // ret 0x18 = 被调者清 6 个 dword
constexpr int32_t kFntSwProbeLen = 16;
constexpr uint8_t kFntSwProbe[kFntSwProbeLen] = {0x83, 0xEC, 0x08, 0x55, 0x8B, 0x6C, 0x24, 0x10,
                                                 0x8B, 0x45, 0x14, 0x56, 0x57, 0x8B, 0xF9, 0x33};
constexpr int32_t kFntSwLayoutOffset = 0x29; // 0x58DF99 - 0x58DF70
