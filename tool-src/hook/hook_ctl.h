//        而原图里植物图案有很亮的像素 ⇒ 亮的地方可以到 **64** (纯白原图 x 0.25);
//        另外 `SeedPacket::Draw` 还有一条 `aGrayness = 128` 的状态
//        (买不起 / 种植条件不满足: `SeedPacket.cpp:653-656`) ⇒ 那一片的卡面被乘 128/255;
//     ④ 我们是**不透明**矩形 (A 恒 0xff, 这是唯一从出厂字节核对过的 alpha), 所以字模里
//        那些 76..128 的边缘像素在亮卡面上就变成**比底色更暗的孤立小方块** ——
//        1x1 档是 1 个像素的点, 2x2 档 (预算降级) 是 **2x2 的点**, 沿笔画边缘规则排列
//        ⇒ 用户看到的就是"规律排列的黑色像素点 / 网点"。这也解释了**"有时"**:
//        只有"暗化层刚好退到数字那一带以下"的那段时间才看得见 (冷却快结束那几秒最明显)。
//
//   ★★ 修法 (只改"哪些墨色允许画出来", 几何/字号/预算阶梯一个字都不动) ★★
//     ① `kCdFontInkFloor` (**墨色下限**): 任何要画出来的矩形, 灰度一律**抬到**这个值。
//        取值 = **游戏能给出的最亮卡面** + 余量: 纯白原图 x 64/255 = 64,
//        x 128/255 = **128** ⇒ 取 160 (= 128 + 32 余量, 也远高于正常冷却态的 64)
//        ⇒ **任何卡面亮度下, 我们的墨色都不会比它更暗** ⇒ 黑点不可能再出现;
//     ② `kCdFontInkMinCover` (**降权阈值**): 抬到下限会"糊"的**极淡**块直接不画
//        (既不加深一点, 也不画成一块灰)。★ 这个值必须**低于字模表里最暗的墨迹像素**
//        (表里最暗 = 76), 否则会开始丢像素、破坏"逐像素全覆盖"这条无空洞判据;
//        这里取 32 (只有覆盖度 < 16% 的块会被丢) ⇒ 现有字模**一个像素都不会丢**
//        (由 recttest 断言: 表里没有 0 < v < kCdFontInkMinCover 的像素);
//     ③ 只抬暗的、不压亮的 ⇒ 满覆盖仍然是**纯白 255**, 灰度仍然**单调**,
//        `2x2 取块内最大` 这条规矩也不用改 (先取块内最大, 再抬下限)。
//   ★ v35 为什么当时没做 alpha 混合: FillRect/DrawRect 的 alpha 是否真的混合(而不是
//     "按 Color(64,64,64)"那套色化)**当时没有证据** ⇒ v35 只走了"不透明 + 抬下限"
//     这条有字节依据的路。★ v36 补上了证据链并改用 alpha (见本文件顶部 v36 段):
//     ① `D3DInterface::PreDraw()` (每次 BeginScene 都跑) 无条件
//        `SetRenderState(ALPHABLENDENABLE, TRUE)` + `SRCALPHA / INVSRCALPHA`,
//        而 `D3DInterface::FillRect()` 把 `Color.mAlpha` 原样写进顶点 diffuse
//        (`RGBA_MAKE(r,g,b,a)`) ⇒ 顶点色按 SRCALPHA 混合;
//     ② 软件 (DDraw) 路径 `DDImage::NormalFillRect()` 自己就按 alpha 混合
//        (`src = color*alpha/256`, `dst = dst*(256-alpha)/256`, `alpha == 255` 走直写快路);
//     ③ `Graphics::DrawRect()` (拿不到 FillRect 时的降级) 内部也是用同一个 `mColor`
//        去调 FillRect ⇒ 两条路都吃 alpha。
//   ★★ v36: 这两条颜色闸门里, **下面的"降权阈值"整条删掉** ★★
//     ① `kCdFontInkFloor`: **只用于 `CDINK_OPAQUE` 回退路径** (PZTK_CD_NOALPHA=1)。
//        正常路径不用它 —— 正常路径的墨色是"白 + A=覆盖度", 与卡面亮度**无关**。
//        保留 160 = 最亮卡面推算值 128 + 32 余量;
//     ② `kCdFontInkMinCover`: **v36 起恒为 0** —— 也就是**没有任何"低于某灰度就跳过"的
//        路径**。v35 取 32 时它恰好没丢现有字模 (最暗墨迹 76), 但那是**运气**;
//        v36 用 `static_assert(kCdFontInkMinCover == 0)` 把"不许有降权阈值"钉死在编译期,
//        再由 recttest 断言"已画 ⊇ 墨迹" + "改下限不减少已画像素数" (反证没有丢像素路径)。
//   ★ 改这里 = 改**画出来的像素颜色** ⇒ 必须升 kVersion 并重编 exe + DLL
//     (颜色算在共享头纯函数 CdGlyphInk 里, 新旧混用会画出两种字)。
// ===========================================================================
constexpr int32_t kCdFontInkFloor = 160;   // ★ 只给 CDINK_OPAQUE 回退路径用 (抬到 >= 最亮卡面)
constexpr int32_t kCdFontInkMinCover = 0;  // ★ v36: 恒 0 = **不存在**"低于它就跳过"的阈值
static_assert(kCdFontInkFloor >= 0 && kCdFontInkFloor <= 255, "ink floor must be a gray value");
static_assert(kCdFontInkMinCover == 0,
              "v36: there must be NO 'skip blocks fainter than X' path -- every inked pixel (coverage "
              "> 0) has to be drawn, otherwise the glyphs get holes (that was the v35 bug)");

// ★ v32/v33: 卡面**最小高度**的编译期自检 —— 让"可画区"里真的放得下字模, 而且下沿仍在费用区之上。
//   卡面标准尺寸是 50x70 (`SeedPacket` 构造); hook_main.cpp 读到的尺寸越界时**退回这个常量**
//   (见那里的 card_w/card_h 兜底)。这里把"可画区高度 >= 字模高"钉在编译期:
//     可画区高 = kCdSunCostTopY - kCdCardMargin - kCdTitleBandH = 54 - 0 - 9 = 45 >= 14 ✓
//     ★ v34: 再扣掉实机目测的下移量 kCdTextDropY(3) ⇒ 数字真正能用的高度 = 42 >= 14 ✓
//   若哪天有人把 kCdTitleBandH (或 kCdTextDropY) 调到 40 以上, 这行会**编译不过**
//   (而不是安静地把数字推到阳光费用区里去)。
static_assert(kCdSunCostTopY - kCdCardMargin - kCdTitleBandH - kCdTextDropY >= kCdDigitMinH,
              "drawable band (title band .. sun cost, minus the calibrated drop) is too short for the "
              "glyph canvas");
// ★ v34: 下移之后**下沿离费用区仍有富余**也必须成立 (不是"刚好不越界") ——
//   3 位数数字组底边 = 卡顶 41 (居中 24/27 + dh 14 + drop 3), 要求离 54 至少留 kCdPanelPad+2 = 3px。
static_assert(kCdSunCostTopY - kCdTitleBandH - kCdTextDropY - kCdDigitMinH >= 3,
              "dropped digit row must keep a visible margin above the sun-cost area");

// ---- v31: **每帧矩形预算** + 聚合阶梯 (v30 的"带阴影/去阴影"阶梯已被取代) ----
//   ① 阴影层**已删除**: `kCdFontShadowGray` / `kCdShadowDx/Dy` / `CdShadowRect()` 全部不再存在。
//      字画在**变暗的卡面**上, 白字 + 一点 AA 边缘就是参考图的效果; 描边/阴影只会产生
//      用户投诉的那圈"粗黑边"。
//   ② **矩形预算**: 逐像素绘制 ⇒ "一帧最多下发多少个矩形"必须钉上限 (绝不因为画字卡住游戏)。
//        ★ 实测 (离线单测打印的同一组数, "99.9" = 单卡最坏):
//            1x1 逐像素: 单卡 **261** 个矩形 (3 x 84 + 9 = 8/9 的墨迹像素)
//            2x2 聚合:   单卡 **~76** 个矩形 (取块内最大灰度)
//        预算 800 : 3 张最坏的卡用 1x1 (783), 第 4 张起降级成 2x2 (每张 ~76 ⇒ 再放 10 张还有余),
//                   10 张卡同时冷却时**全部**能显示 (前几档清晰、后面的档位略糊)。
//                   ★ 为什么仍是 800 (而不是"按新渲染调大"): 每个矩形 = 一次 SetColor + FillRect
//                   (游戏的 FillRect 要么是一次 D3D DrawPrimitive, 要么是 DDImage 的一次
//                   surface 锁 + 写像素) ⇒ 预算越大, "卡住游戏"的风险越大; 而 v30 的 800
//                   已经在**用户实机**上跑过且没有任何卡顿反馈 ⇒ 保持同一个已验证的开销包线,
//                   靠**阶梯**去适配 1x1 这种更贵的档位, 而不是靠调大预算。
//        上限 2700: = **10 张卡 x 单卡最坏 (1x1)** 的保守上界 (10 x 261 = 2610 <= 2700;
//                   按最胖的字符 '8' 算就是 10 x (3 x 91 + 9) = 2820 —— 那是"整版全是 8"的
//                   极端值, 所以取 2700 并**只在单测里**断言真正的产线组合 "99.9" 不越界)。
//                   ⇒ 离线单测断言 "10 张卡 x 单卡最坏 1x1 <= 硬上限" + "预算 <= 硬上限"。
//      降级顺序 (在 CooldownDrawInGame 里用共享头纯函数 CdPickStep 实现, 顺序不能反):
//        ① 1x1 逐像素够画 ⇒ 画 (最清晰);
//        ② 不够 ⇒ **这一张卡**改成 2x2 聚合 (取块内最大灰度 ⇒ 灰度仍然单调), 其余卡继续;
//        ③ 2x2 也不够 ⇒ 这张卡整张不画, 记 CDSKIP_BIT_BUDGET (宁可少一张)。
//      ★ 每一步都**先问"够不够"再画** ⇒ 本帧矩形数**永远 <= 预算** (由离线单测的阶梯断言钉住)。
constexpr int kCdRectBudget = 800;
constexpr int kCdRectBudgetHardMax = 2700;

struct CdTextGeom
{
    int32_t ndig;    // 数字个数 (不含小数点), 2 或 3
    int32_t dw;      // 单个数字的包围盒宽 (= 字模画布宽 kCdFontCanvasW)
    int32_t dh;      // 单个数字的包围盒高 (= 字模画布高 kCdFontCanvasH)
    int32_t stroke;  // ★ v30 起**已废弃**: 字模是位图, 没有"段粗"。留着只为诊断行布局
    int32_t gap;     // 相邻字符包围盒之间的空隙
    int32_t dot_w;   // 小数点宽 (= dw: 小数点也用同一张字模表里的一格)
    int32_t total_w; // 整组字符 (ndig 个数字 + 小数点) 的包围盒宽
};

// 由"可用宽/高 + 数字个数"**反算**几何 (硬规矩 ②); 放不下 (比最小尺寸还小) 返回 false。
constexpr bool CdTextGeomMake(int32_t avail_w, int32_t avail_h, int32_t ndig, CdTextGeom &out)
{
    out.ndig = ndig;
    out.dw = 0;
    out.dh = 0;
    out.stroke = 0;
    out.gap = kCdDigitGap;
    out.dot_w = 0; // 与 dw 相同, 见下面 (小数点也用字模表里的那一格)
    out.total_w = 0;
    if (ndig < 1 || ndig > kCdMaxDigits || avail_w <= 0 || avail_h <= 0)
        return false;
    // ① 按可用宽度反算: ndig 个数字 + 1 个小数点 + ndig 个空隙 <= avail_w
    //    ★ v30: 小数点也是一个**完整格子** (它有自己的字模), 所以它按 kCdAspectW 的
    //      宽高比参与"每一格"的宽度 —— 下面按 ndig+1 格一起反算。
    const int32_t cells = ndig + 1; // 数字 + 小数点
    const int32_t room = avail_w - cells * kCdDigitGap;
    if (room <= 0)
        return false;
    int32_t dw = room / cells;
    // ② 按可用高度反算 (宽高比 = 字模表的 10:14)
    const int32_t dw_by_h = avail_h * kCdAspectW / kCdAspectH;
    if (dw > dw_by_h)
        dw = dw_by_h;
    // ③ 不超过设计目标尺寸 —— 默认就该"小而清楚", 只有放不下才继续缩
    if (dw > kCdDigitTargetW)
        dw = kCdDigitTargetW;
    if (dw < kCdDigitMinW)
        return false;
    int32_t dh = dw * kCdAspectH / kCdAspectW;
    if (dh > avail_h)
        dh = avail_h;
    if (dh < kCdDigitMinH)
        return false;
    out.dw = dw;
    out.dh = dh;
    // ④ v30: 段粗已经不需要了 (字模是位图), 保留字段只为**诊断行**兼容 ——
    //    报成"笔画高度的上界"= 1 会让用户以为字变细了, 所以报字模的**灰度级数**
    //    没有意义; 这里报 0 并在界面文案里说明"字模不再是七段"。
    out.stroke = 0;
    out.dot_w = dw; // ★ 小数点与数字同宽 (同一张字模表, 同一格子)
    // total = (ndig+1)*dw + cells*gap <= room + cells*gap = avail_w ✓ 不溢出
    out.total_w = cells * dw + cells * kCdDigitGap;
    return true;
}

// ---- 两个矩形小工具 (纯函数, 断言"不重叠/在内部"时用同一套判据) ----
constexpr bool CdRectEmpty(const CardRect &r) { return r.w <= 0 || r.h <= 0; }

constexpr bool CdRectInside(const CardRect &inner, const CardRect &outer)
{
    if (CdRectEmpty(inner))
        return false;
    return inner.x >= outer.x && inner.y >= outer.y && inner.x + inner.w <= outer.x + outer.w &&
           inner.y + inner.h <= outer.y + outer.h;
}

// 相交 (半开区间: 边挨边不算相交 —— 我们要求的是"留缝", 由调用方另加空隙)
constexpr bool CdRectOverlap(const CardRect &a, const CardRect &b)
{
    if (CdRectEmpty(a) || CdRectEmpty(b))
        return false;
    return a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h;
}

// 阳光计数器矩形 (SeedBank 空间 ⇒ 传入 bank 自己的 mX/mY; 它会跟着卡槽一起滑动)
constexpr CardRect CdSunCounterRect(int32_t bank_x, int32_t bank_y)
{
    return CardRect{bank_x + kCdSunCounterCenterX - kCdSunCounterHalfW, bank_y + kCdSunCounterTopY,
                    2 * kCdSunCounterHalfW, kCdSunCounterH};
}

// 卡上的阳光费用矩形 (禁画区; 卡面 [卡顶+54, 卡底))
constexpr CardRect CdSunCostRect(const CardRect &card)
{
    const int32_t top = card.y + kCdSunCostTopY;
    int32_t h = card.y + card.h - top;
    if (h < 0)
        h = 0;
    return CardRect{card.x, top, card.w, h};
}

// 可画区 (= 诊断里说的"位置外框"的最大范围): **卡面标题条以下、阳光费用区以上**, 离卡面边缘 kCdCardMargin
//   ★★ v32: 上边界从"卡面下半部 (`card.h+1)/2` = 35)"改成 **卡顶 + kCdTitleBandH** (当时 = 30)。
//     为什么: 用户 v31 的反馈是"数字要上下居中", 而"可画区"的字面语义就是
//     **标题条以下、费用区以上** (见 kCdTitleBandH 的证据链) —— 用"卡面下半部"当上边界,
//     数字组的中心会落在卡顶 + 44.5 (偏低 2.5px), 那正是 v31 的位置。
//   ★★ v33: 上界的**数值**从 30 收到 **9** —— 30 只是"上半部是标题条"的粗略估计 (厚了一倍),
//     实机看着数字贴着费用区 (用户第二轮反馈"往上移")。9 = 从实机卡片截图上量出来的
//     **植物图案区上沿** (标题条横幅最后一行是 6, 7..8 是它的深色下沿) ⇒ 可画区 = 卡顶 9..54。
//     只改常量, 算式与下边界一个字节都没动。
//   ★ 下边界仍然是 **卡顶 + 54 (阳光费用墨迹上沿) - kCdCardMargin**, 与 v29 一致 ——
//     v31 的"绝不遮挡阳光费用"这条硬规矩**没有**放宽 (由 CdPlaceGate + recttest 逐卡断言)。
//   ★★ v34: **这个函数一个字都没改** —— 可画区仍是 卡顶 9..54 (中心 31)。
//     "再下移 3px" 是**数字组自己的**实机目测校准量 (`kCdTextDropY`), 加在 `CdTextRect` 里;
//     禁画区边界 (`kCdTitleBandH` / `kCdSunCostTopY`) 与可画区语义**保持原样** ⇒
//     "数字不许压标题条 / 不许压阳光费用"这两条判据的基准没被污染。
constexpr CardRect CdPanelArea(const CardRect &card)
{
    const int32_t top = card.y + kCdTitleBandH;                    // 标题条以下
    const int32_t bottom = card.y + kCdSunCostTopY - kCdCardMargin; // 费用区上沿 - 边距
    int32_t w = card.w - 2 * kCdCardMargin;
    int32_t h = bottom - top;
    if (w < 0)
        w = 0;
    if (h < 0)
        h = 0;
    return CardRect{card.x + kCdCardMargin, top, w, h};
}

// 数字**本身**允许的范围 = 可画区再内缩 kCdPanelPad (外框包着数字)
//   ★ v32: 它只用来"反算字号"与"保证外框也在卡面内", **不再**当垂直居中的基准
//     (v31 就是拿它居中 ⇒ 数字整体偏下 2.5px; 见 CdTextRect 的说明)。
constexpr CardRect CdDigitArea(const CardRect &card)
{
    const CardRect a = CdPanelArea(card);
    int32_t w = a.w - 2 * kCdPanelPad;
    int32_t h = a.h - 2 * kCdPanelPad;
    if (w < 0)
        w = 0;
    if (h < 0)
        h = 0;
    return CardRect{a.x + kCdPanelPad, a.y + kCdPanelPad, w, h};
}

// 整组数字 (含小数点) 的包围盒: 水平**卡面居中**, 垂直在**可画区**里居中 (v32 硬规矩 ⑧)
//   ★★ v32 的垂直算式 (用户要求"上下居中", 容差 <= 1px, 由 recttest 逐个数字个数断言) ★★
//     ① 可画区的垂直中心:  `center = area.y + area.h / 2`
//        (area = CdPanelArea = 卡顶+9 .. 卡顶+54 ⇒ 卡顶 + 31; 高 45 是奇数 ⇒ 向下取整到 22)
//     ② 数字组左上角:      `y = center + kCdTextDropY - (g.dh + 1) / 2`
//        ⇒ y + dh/2 == center + kCdTextDropY (dh 为偶数 ⇒ 精确; 奇数时偏差 <= 1)
//     ★ 为什么刻意**不用** CdDigitArea (内缩 1px 那个): 内缩是为了"外框也别贴到卡面边",
//       不是"数字要往里挪" —— 拿它居中正好把数字往下挪半格 (v31 的 44.5 vs 42)。
//     ★ 垂直居中与"绝不遮阳光"并不冲突: 可画区 (9..54) 本身就完全在费用区 (54..70) 之上,
//       这与 v31 一样由 CdPlaceGate 逐卡断言 (数字 27..40、外框 26..41, 都碰不到 54)。
//   ★★ v34: 算式**结构一个字都没改** —— 还是在可画区里居中, 只在最后加了一条
//     `+ kCdTextDropY` (3px, **用户实机目测校准值**: "还要下移 3px", 用户自己数过像素)。
//     于是数字组从 卡顶 24..37 变成 **27..40**; 这 3px **不追求几何绝对居中**
//     (上下留白由 15:16 变成 18:13), 别拿"对称"去"修"它 —— recttest 的判据也跟着改成
//     "垂直中心 == 可画区中心 + kCdTextDropY", 而不是"== 可画区中心"。
constexpr CardRect CdTextRect(const CdTextGeom &g, const CardRect &card)
{
    if (g.total_w <= 0 || g.dh <= 0)
        return CardRect{card.x, card.y, 0, 0};
    const CardRect area = CdPanelArea(card);
    const int32_t center_y = area.y + area.h / 2 + kCdTextDropY;
    return CardRect{card.x + (card.w - g.total_w) / 2, center_y - (g.dh + 1) / 2, g.total_w, g.dh};
}

// ---- 字符格子几何 (v31 的**唯一一份**实现) ----
//   ★ 整组字符占 ndig+1 个**同宽同高**的格子 (ndig 个数字 + 1 个小数点), 相邻格子
//     之间固定 kCdDigitGap 个像素的空隙, 第 cell 个格子的左上角 = CdTextRect 的左上角
//     + cell x (dw + gap)。
constexpr CardRect CdCellRect(const CdTextGeom &g, const CardRect &card, int32_t cell)
{
    const CardRect t = CdTextRect(g, card);
    if (CdRectEmpty(t) || g.dw <= 0)
        return CardRect{t.x, t.y, 0, 0};
    return CardRect{t.x + cell * (g.dw + g.gap), t.y, g.dw, g.dh};
}

// 至少能放几个格子 (ndig + 1) —— 调用方与单测都用它遍历, 不要自己写 "+1"
constexpr int32_t CdCellCount(const CdTextGeom &g) { return g.ndig + 1; }

// ★★ v31 关键修正: 显示顺序 = **最高位..个位, 小数点, 十分位** ★★
//   v30 把小数点画在整组**最后** ⇒ 实机显示的是 `350.` 而不是 `35.0`
//   (用户截图里的 `85.` 就是这么来的: 应该是 `8.5`)。这个坑只在"字符顺序"里,
//   几何、闸门、预算全都看不出来 —— 所以把顺序也做成**共享头纯函数**:
//     第 cell 个格子里到底是哪个字符, **只有这一份**实现。
//   digits_hi[] 是**从左到右**的字符 (digits_hi[0] = 最高位, digits_hi[ndig-1] = 十分位)。
constexpr char CdDisplayChar(const CdTextGeom &g, const char *digits_hi, int32_t cell)
{
    if (digits_hi == nullptr)
        return '\0';
    if (cell < 0 || cell > g.ndig)
        return '\0';
    if (cell == g.ndig - 1)
        return '.';                 // 小数点: 正好在"个位"与"十分位"之间
    if (cell < g.ndig - 1)
        return digits_hi[cell];     // 最高位..个位
    return digits_hi[g.ndig - 1];   // 十分位 (整组的最后一格)
}

// ---------------------------------------------------------------------------
// ★★ v38: 原生路径的**字符串构造** —— 与矩形路径的 CdDisplayChar 同一个顺序 ★★
//
//   为什么必须做成共享头的纯函数 (而不是留在 hook_main.cpp 里):
//     ① 顺序**只有一份**实现 —— 原生路径 (一次 DrawString 画整串) 与矩形路径
//        (逐格画 CdDisplayChar) 必须给出**同一个**字符串, 否则两条路画出来的东西不一样;
//     ② 离线单测 (recttest) 才能直接断言它 —— 本机没有可运行的游戏。
//
//   ★★ 实机 bug (v37 -> v38): 小数点**右移一位** ★★
//     v37 的 BuildCdText 把 `chars_hi[0..ndig-1]` **全部**抄了一遍 (可它最后一个元素
//     已经是"十分位"), 然后又补 `.` 和十分位 ⇒ `35.0` 变成 **`350.0`**、
//     `12.4` 变成 **`124.4`** (小数点整整右移一格, 末尾还多出一个字符)。
//     根因是"生产者/消费者对 `digits_hi` 的约定不一致":
//       生产端 (hook_main.cpp 第一趟) 填的是 `最高位..十分位` (共 ndig 个 —— 与
//       CdDisplayChar 的用法一致: 小数点插在第 `ndig-1` 格**之前**);
//       而 v37 的 BuildCdText 却按注释里的 "最高位..个位 + 十分位" 去用 (共 ndig+1 个)。
//     ⇒ 现在**只用一份约定**: 逐格调用 CdDisplayChar ⇒ 两条路不可能再分叉。
//
//   返回串长 (= ndig + 1, 与 CdCellCount 相同); 0 = 输入不合法 (调用方必须拒, 绝不画半个数)。
//   最长 "99.9" = 4 字符 ⇒ 永远远小于 SSO 的 15 字节上限。
constexpr int32_t CdTextCharsBuild(int32_t ndig, const char *digits_hi, char *out, int32_t cap)
{
    if (digits_hi == nullptr || out == nullptr)
        return 0;
    if (ndig < 1 || ndig > kCdMaxDigits)
        return 0;
    if (cap < ndig + 2) // ndig+1 个字符 + 结尾 NUL
        return 0;
    // ★ 源数组必须是**纯数字**: 小数点由本函数插进去 ⇒ 源里出现 '.' 就说明调用方
    //   又按另一套约定填了数组 (v37 那个 bug 的成因), 宁可拒绝也不画。
    for (int32_t i = 0; i < ndig; i++)
    {
        if (digits_hi[i] < '0' || digits_hi[i] > '9')
            return 0;
    }
    CdTextGeom g{};
    g.ndig = ndig;
    for (int32_t cell = 0; cell <= ndig; cell++)
        out[cell] = CdDisplayChar(g, digits_hi, cell);
    out[ndig + 1] = '\0';
    return ndig + 1;
}

// 小数点在这一串里的下标 (= **个位那一格的右边**) —— 与矩形路径的 CdDotRect 同一格。
//   ★ 两条路的小数点位置**只由这一个式子**决定 (recttest 断言"串里的下标 == 格子下标")。
constexpr int32_t CdDotIndex(int32_t ndig) { return ndig - 1; }

// 第 i 个格子的包围盒 (i = 0 最左 = **最高位**)。★ 名字保留只为兼容:
//   它返回的是"格子", 不是"第 i 个数字" —— 小数点那一格在 ndig-1 (见 CdDisplayChar)。
constexpr CardRect CdDigitRect(const CdTextGeom &g, const CardRect &card, int32_t i)
{
    return CdCellRect(g, card, i);
}

// 小数点的包围盒 (= 第 ndig-1 个格子; v30 是第 ndig 个那格, 位置错了 ⇒ 实机显示 `350.`)
constexpr CardRect CdDotRect(const CdTextGeom &g, const CardRect &card)
{
    if (g.ndig < 1)
        return CardRect{card.x, card.y, 0, 0};
    return CdCellRect(g, card, g.ndig - 1);
}

// 底衬外框 = 整组数字外扩 kCdPanelPad
//   ★ v31: 这个矩形**不再被填充** (用户投诉的"粗黑边"有一半来自这层黑底衬)。
//     它现在的身份是"位置闸门与诊断用的外框": 数字必须连它一起落在卡面内。
constexpr CardRect CdPanelRect(const CdTextGeom &g, const CardRect &card)
{
    const CardRect t = CdTextRect(g, card);
    if (CdRectEmpty(t))
        return t;
    return CardRect{t.x - kCdPanelPad, t.y - kCdPanelPad, t.w + 2 * kCdPanelPad, t.h + 2 * kCdPanelPad};
}

// ---- 字模 -> **逐像素矩形 (可聚合成 2x2 块)** (v31 起**唯一一份**"画什么"实现) ----
//   ★★ 为什么做成纯函数 ★★
//     运行期绘制 (hook_main.cpp) 与离线单测 (recttest.cpp) 都调这一个函数:
//     单测断言的"矩形数"就是出厂代码真的会下发的那个数, 不存在"照着抄一遍"。
//   ★ 约束: 字模**不缩放**。表里的画布是 10x14, 而 CdTextGeomMake 反算出来的格子也是
//     10x14 (同一个 kCdAspectW:H) ⇒ 正常卡面上 1:1 直接画。格子尺寸对不上时返回 0
//     (= 这张卡不画) —— 绝不用最近邻缩放去糊 (那会把抗锯齿边缘毁掉, 正是要修的东西)。
//   ★ 聚合 (`step`): 1 = 一个像素一个矩形 (最清晰); 2 = 2x2 一块, 灰度取块内**最大值**。
//     取最大值有两个好处: ① **灰度单调** —— 全白的块画出来还是纯白, 不会被邻居"拉灰"
//     (取平均就会把白边变灰, 那正是用户投诉的"方块/发灰"观感); ② 边缘不会变暗。
//     块在画布边缘处自动裁剪 (w/h 可能只有 1), 所以永远不会画出格子外。
//   ★★ v35: 每个块的灰度还要过颜色闸门 (顺序: 先取块内最大, 再抬下限) ★★
//     ① `kCdFontInkFloor`: 灰度**抬到**下限 —— 字模的边缘墨色是按"变暗的卡面 (64)"标定的,
//        而暗化层收缩后卡面会亮到 128 (原图 x 128/255) ⇒ 不抬就是"比底色更暗的点"
//        (实机投诉的"规律排列的黑色像素点"); 抬到 160 之后**任何卡面亮度下都不会更暗**;
//     ② `kCdFontInkMinCover`: 太淡的块**不画** (既不加深也不画灰)。
//     ③ 抬下限是**单调**的: 只抬暗的、不压亮的 ⇒ 满覆盖仍是纯白 255,
//        `CdGlyphGraysMono()` 那条"2x2 灰度 >= 1x1 灰度"的判据照样成立。
//     ★ 这两道闸门在**共享头**里 ⇒ 运行期绘制与离线单测跑的是同一份;
//   ★★ v36 改动: 上面的 ② **整条删掉** (它是一条"低于某灰度就不画"的丢像素路径 ⇒ 会挖洞),
//     ① 降级成**只在 CDINK_OPAQUE 回退路径**里用。默认路径改成"白字 + A = 覆盖度"的
//     alpha 混合 (见下面 CdGlyphInk 的说明) —— 与卡面亮度**无关**, 因此既不会有黑点,
//     也不会有洞 (覆盖度 > 0 的像素**一律**被画出来)。
struct CdBlock
{
    int32_t x;    // 相对格子左上角的 x 偏移
    int32_t y;    // 相对格子左上角的 y 偏移
    int32_t w;    // 1..step
    int32_t h;    // 1..step
    uint8_t gray; // ★ v36: 要写进画面的**分量值**: alpha 档 = 255 (纯白); 回退档 = 抬过下限的灰
    uint8_t alpha; // ★ v36: 要写进画面的 alpha: alpha 档 = 该块内**最大覆盖度** (1..255); 回退档 = 255
};

// 一次调用最多产出多少个块 (调用方按它开栈数组): 1x1 = 整块画布, 2x2 = 每 2x2 一块
constexpr int32_t kCdGlyphMaxBlocks1 = kCdFontCanvasW * kCdFontCanvasH;
constexpr int32_t kCdGlyphMaxBlocks2 = ((kCdFontCanvasW + 1) / 2) * ((kCdFontCanvasH + 1) / 2);
constexpr int32_t CdGlyphMaxBlocks(int32_t step)
{
    return (step <= 1) ? kCdGlyphMaxBlocks1 : kCdGlyphMaxBlocks2;
}
// 栈数组的通用上界 (1x1 那一档最大)
constexpr int32_t kCdGlyphMaxBlocks = kCdGlyphMaxBlocks1;

// ---------------------------------------------------------------------------
// ★★ v36: "某个字模灰度最终画成什么颜色" —— **只有这一份实现** (纯函数, 离线可断言) ★★
//
//   两个模式 (运行期由环境变量 PZTK_CD_NOALPHA 选, 见 hook_main.cpp):
//     * `CDINK_ALPHA`  (**默认**) 白字 + A = 覆盖度 ⇒ 与卡面亮度**无关**的正确混合;
//     * `CDINK_OPAQUE` (回退)    不透明灰 = max(表值, kCdFontInkFloor), A = 255。
//   两个模式**发出去的块集合完全一样** (都是"块内最大灰度 != 0"的那些块) ⇒
//   "已画 ⊇ 墨迹"这条硬不变量与模式无关 (recttest 对两种模式都断言)。
//
//   ① `CdGlyphCoverage(v)`: 表里的灰度 v → **覆盖度** (0..255)。
//      生成器的正变换是 `v = kCdFontGrayBg + 覆盖度 x (255-kCdFontGrayBg) / 255`
//      (见 cd_font.h 表头) ⇒ 这里就是它的**反函数**。v == 0 (透明) ⇒ 0;
//      任何 v > 0 ⇒ **>= 1** (绝不会把有墨的像素变成"完全透明")。
//   ② `CdGlyphGrayPaint(v)`: v35 的"抬下限" —— **只给 CDINK_OPAQUE 回退路径用**。
//   ③ `CdGlyphInk(v, mode)`: 唯一的"墨色 → (gray, alpha)"映射 (v = 块内最大灰度)。
//      v == 0 ⇒ {0, 0} = **不画** —— 这是**唯一**允许不画的情形。
//   ④ `CdGlyphGraysMono` / `CdGlyphInkMono`: 单调判据 (2x2 聚合档画出来的灰度/alpha
//      都不会比它覆盖的 1x1 像素更小) —— 由 recttest 对全表逐块交叉断言。
// ---------------------------------------------------------------------------
enum CdInkMode : int32_t
{
    CDINK_ALPHA = 0,  // 默认: 白字 (255,255,255) + A = 覆盖度
    CDINK_OPAQUE = 1, // 回退 (PZTK_CD_NOALPHA=1): 不透明灰 + A = 255
};
static_assert(CDINK_ALPHA == 0, "the default ink mode must be alpha (the env switch is opt-OUT)");

constexpr uint8_t CdGlyphCoverage(uint8_t v)
{
    if (v == 0)
        return 0;
    if (v <= static_cast<uint8_t>(kCdFontGrayBg))
        return 1; // 理论上不会出现 (表里最暗 76 > 64); 兜底也**绝不返回 0**
    int32_t a = (static_cast<int32_t>(v) - kCdFontGrayBg) * 255 / (255 - kCdFontGrayBg);
    if (a < 1)
        a = 1;
    if (a > 255)
        a = 255;
    return static_cast<uint8_t>(a);
}

constexpr uint8_t CdGlyphGrayPaint(uint8_t v)
{
    if (v == 0)
        return 0;
    return (v < static_cast<uint8_t>(kCdFontInkFloor)) ? static_cast<uint8_t>(kCdFontInkFloor) : v;
}

struct CdInk
{
    uint8_t gray;  // 0 = 不画 (只可能是"这个块全透明")
    uint8_t alpha; // 0 = 不画
};

constexpr CdInk CdGlyphInk(uint8_t v, int32_t mode)
{
    // ★ C++17 的 constexpr 函数里局部变量必须**声明即初始化** (不能先声明再赋值)
    if (v == 0)
        return CdInk{0, 0}; // ★ 唯一的"不画"理由: 这个块一个墨迹像素都没有
    if (mode == CDINK_OPAQUE)
    {
        // 回退: 不透明 + 抬到下限 (**照画**, 不是跳过)
        return CdInk{CdGlyphGrayPaint(v), 255};
    }
    // 默认: 白字 + A = 覆盖度 ⇒ 输出 = 底色 + (255-底色) x A / 255, 永远不暗于底色
    return CdInk{255, CdGlyphCoverage(v)};
}

constexpr bool CdGlyphGraysMono(uint8_t gray_step1, uint8_t gray_step2)
{
    return gray_step2 >= gray_step1;
}

constexpr bool CdGlyphInkMono(CdInk a, CdInk b)
{
    return CdGlyphGraysMono(a.gray, b.gray) && CdGlyphGraysMono(a.alpha, b.alpha);
}

// 把字符 c 的字模展开成矩形块; 返回块数。
//   ★ 返回值 0 = 这个字符没有字模 / 格子尺寸不匹配 / step 不是 1 或 2 ⇒ **这张卡不画**。
//   ★ `out == nullptr` 表示**只数不落数组** (同一份实现, 所以"数出来的"与"画出来的"永远一致);
//     此时 cap 被忽略, 返回值就是"要下发多少个矩形"。
//   ★★ v36 硬不变量: 画布上**任何覆盖度 > 0 的像素**都必须被画到 ★★
//     (1x1 档 = 那个像素自己有一个 1x1 块; 2x2 档 = 它所属的那个块必须被画)。
//     实现上只有一条 `if (gray == 0) continue;` —— **没有任何按灰度大小丢块的路径**。
constexpr int32_t CdGlyphBlocks(char c, int32_t cw, int32_t ch, int32_t step, CdBlock *out,
                                int32_t cap, int32_t mode = CDINK_ALPHA)
{
    const bool count_only = (out == nullptr);
    if (!count_only && cap <= 0)
        return 0;
    // 字模不缩放: 格子必须**正好**是画布尺寸
    if (cw != kCdFontCanvasW || ch != kCdFontCanvasH)
        return 0;
    if (step != 1 && step != 2)
        return 0; // 只有这两档 (要加档位必须先扩桌面上的预算与单测)
    const int32_t gi = CdFontIndexOf(c);
    if (gi < 0)
        return 0;
    const uint8_t *px = cd_glyph_px + gi * (kCdFontCanvasW * kCdFontCanvasH);
    int32_t n = 0;
    for (int32_t by = 0; by < kCdFontCanvasH; by += step)
    {
        int32_t bh = kCdFontCanvasH - by;
        if (bh > step)
            bh = step;
        for (int32_t bx = 0; bx < kCdFontCanvasW; bx += step)
        {
            int32_t bw = kCdFontCanvasW - bx;
            if (bw > step)
                bw = step;
            uint8_t gray = 0;
            for (int32_t y = 0; y < bh; y++)
            {
                const uint8_t *row = px + (by + y) * kCdFontCanvasW + bx;
                for (int32_t x = 0; x < bw; x++)
                    if (row[x] > gray)
                        gray = row[x]; // ★ 取最大 ⇒ 灰度/覆盖度单调 (白不会被邻居拉灰)
            }
            if (gray == 0)
                continue; // ★★ 唯一的"不画"理由: 这个块**全透明** ★★
            const CdInk ink = CdGlyphInk(gray, mode);
            if (!count_only)
            {
                if (n >= cap)
                    return n; // 容量不够就停在这里 (调用方按 CdGlyphMaxBlocks 开数组, 不会发生)
                out[n].x = bx;
                out[n].y = by;
                out[n].w = bw;
                out[n].h = bh;
                out[n].gray = ink.gray;
                out[n].alpha = ink.alpha;
            }
            n++;
        }
    }
    return n;
}

// 字模表里**最暗的墨迹像素** (0 = 透明不算) —— 用来记录"抬下限到底影响多少像素"。
// v36 起它**不再**用来给"降权阈值"做下界 (那个阈值已经删掉了)。
constexpr uint8_t CdFontMinInkGray()
{
    uint8_t mn = 255;
    bool any = false;
    for (int32_t i = 0; i < kCdFontCharCount; i++)
    {
        const uint8_t *px = cd_glyph_px + i * (kCdFontCanvasW * kCdFontCanvasH);
        for (int32_t k = 0; k < kCdFontCanvasW * kCdFontCanvasH; k++)
        {
            if (px[k] == 0)
                continue;
            any = true;
            if (px[k] < mn)
                mn = px[k];
        }
    }
    return any ? mn : 0;
}


// 单个字符要下发多少个矩形 (只数, 与 CdGlyphBlocks 同一份实现)
//   ★ step = 1 时它正好等于"这个字符的墨迹像素数" (= cd_font.h 的 kCdFontInkPixels)。
//   ★ v36: 与墨色模式无关 (两个模式发出去的块集合一样; 只有 gray/alpha 取值不同)。
constexpr int32_t CdGlyphBlockCount(char c, int32_t step, int32_t mode = CDINK_ALPHA)
{
    return CdGlyphBlocks(c, kCdFontCanvasW, kCdFontCanvasH, step, nullptr, 0, mode);
}

// 单个字符的**墨迹像素数** (0 < gray 的像素个数; 与 kCdFontInkPixels 对得上才算表没坏)
constexpr int32_t CdGlyphInkPixels(char c)
{
    const int32_t gi = CdFontIndexOf(c);
    if (gi < 0)
        return 0;
    const uint8_t *px = cd_glyph_px + gi * (kCdFontCanvasW * kCdFontCanvasH);
    int32_t n = 0;
    for (int32_t i = 0; i < kCdFontCanvasW * kCdFontCanvasH; i++)
        if (px[i] != 0)
            n++;
    return n;
}

// ★★ v36 编译期自检: **不存在**"低于某个灰度就不画"的路径 ★★
//   v35 曾经有一条 `gray >= kCdFontInkMinCover(32)` 的降权阈值: 它恰好没丢现有字模
//   (表里最暗墨迹 76), 但那只是**运气** —— 任何一次字体重生成/改字号都可能产出
//   0 < v < 32 的墨迹像素, 那些像素会被**直接丢掉** = 字形上出现规则空洞。
//   v36 把它钉死成 0 (唯一的"不画"理由是整块透明), 并由 recttest 断言
//   "已画 ⊇ 墨迹" (两档 x 12 字符 x 两模式) 与 "改下限不减少已画像素数"。
static_assert(kCdFontInkMinCover == 0,
              "v36: the 'skip faint blocks' gate is gone; a non-zero threshold would start dropping "
              "real ink pixels again (= holes in the glyphs)");
static_assert(CdFontMinInkGray() > 0, "the glyph table must not be empty");

// 整组字符 ("ndig 个数字 + 小数点") 的矩形总数 = **本帧要下发的矩形数** (某一张卡)。
//   digits_hi[] 是**从左到右**的字符 (digits_hi[0] = 最高位 = 十分位在最后), 见 CdDisplayChar。
//   ★ 0 表示"这组字符画不出来" (字符不在表里 / 格子尺寸不符) ⇒ 调用方跳过这张卡。
//   ★ v36: 块数与墨色模式**无关** (两个模式发出去的块集合完全一样) —— 由 recttest 断言。
constexpr int32_t CdTextBlockCount(const CdTextGeom &g, const char *digits_hi, int32_t step,
                                   int32_t mode = CDINK_ALPHA)
{
    if (digits_hi == nullptr)
        return 0;
    int32_t n = 0;
    for (int32_t cell = 0; cell <= g.ndig; cell++)
    {
        const char c = CdDisplayChar(g, digits_hi, cell);
        const int32_t k = CdGlyphBlockCount(c, step, mode);
        if (k <= 0)
            return 0; // 有任何一个字符解不出来 ⇒ 整组不画 (绝不画半个数字)
        n += k;
    }
    return n;
}

// ---------------------------------------------------------------------------
// 两道闸门 (纯函数 ⇒ 离线单测跑的就是生产逻辑, 见 recttest.cpp)
//
//   ★★ 硬规矩: **FillRect 不是前置条件** ★★
//     v26 的闸门写成 `set_color==0 || draw_rect==0 || fill==0 ⇒ return`, 而工具侧
//     从来没有下发过 FillRect ⇒ `fill` 恒为 0 ⇒ **一行都画不出来**, 而且界面还显示
//     "已生效" (那只看钩点自检)。这条闸门现在**连 fill 参数都不收** ——
//     拿不到实心填充就降级成描边, 绝不允许"缺一个可选 API ⇒ 整帧放弃"。
// ---------------------------------------------------------------------------
constexpr uint32_t CdFrameGate(int32_t cd_on, uint32_t set_color_addr, uint32_t draw_rect_addr,
                               int32_t board_readable, uint32_t bank_ptr, int32_t bank_readable,
                               int32_t count)
{
    if (cd_on == 0)
        return CDSKIP_BIT_OFF;
    if (set_color_addr == 0 || draw_rect_addr == 0)
        return CDSKIP_BIT_NO_ADDR;
    if (board_readable == 0)
        return CDSKIP_BIT_BOARD;
    if (bank_ptr < 0x10000u)
        return CDSKIP_BIT_BANK;
    if (bank_readable == 0)
        return CDSKIP_BIT_UNREADABLE;
    if (count <= 0 || count > kMaxSeedPackets)
        return CDSKIP_BIT_COUNT;
    return CDSKIP_NONE;
}

// ---- 聚合档位 (降级阶梯) ----
//   ① CDSTEP_BLOCK1 = 1x1 逐像素 (最清晰);
//   ② CDSTEP_BLOCK2 = 2x2 聚合 (块内取最大灰度, 仍然单调);
//   ③ CDSTEP_SKIP   = 这张卡不画 (记 CDSKIP_BIT_BUDGET)。
//   ★ v30 的"带阴影 / 去阴影"两档**已删除**: 阴影层不再存在。
enum CdDrawStep : int32_t
{
    CDSTEP_SKIP = 0,
    CDSTEP_BLOCK1 = 1,
    CDSTEP_BLOCK2 = 2,
};

// ★★ 单卡档位 (纯函数): "这一张卡该用哪一档" ★★
//   ★ 出厂 DLL 的**整帧分配**用的是下面的 CdAllocSteps (先给每张卡占 2x2, 再升级成 1x1);
//     本函数是"只看这一张卡"的等价形式, 供**离线单测**做交叉核对
//     (单测断言: 单卡情形下两者给出同一档 —— 免得哪天两份阶梯悄悄分歧)。
//   "本帧已经下了多少个矩形" + "本帧预算" 进去, 该用哪一档出来。
//   ★ 顺序不能反, 而且**每一步都先问够不够**。
constexpr int32_t CdPickStep(const CdTextGeom &g, const char *digits_hi, int32_t rects_used,
                             int32_t budget)
{
    const int32_t n1 = CdTextBlockCount(g, digits_hi, CDSTEP_BLOCK1);
    if (n1 > 0 && rects_used + n1 <= budget)
        return CDSTEP_BLOCK1;
    const int32_t n2 = CdTextBlockCount(g, digits_hi, CDSTEP_BLOCK2);
    if (n2 > 0 && rects_used + n2 <= budget)
        return CDSTEP_BLOCK2;
    return CDSTEP_SKIP;
}

// ---------------------------------------------------------------------------
// 本帧的档位分配 (纯函数 ⇒ 离线单测跑的就是出厂逻辑)
//   输入: 每张**能画**的卡两档各要多少矩形 (n1 = 1x1 逐像素, n2 = 2x2 聚合;
//         <= 0 表示这张卡根本不可画 —— 原因位在别处, 这里只当成"不参与");
//   输出: steps_out[] 填 CDSTEP_*; 返回本帧**实际**会下发的矩形总数 (<= budget)。
//
//   ★★ 为什么不是"一张一张地贪心" ★★
//     v31 的第一版就是最朴素的贪心 (能 1x1 就 1x1, 不够就 2x2, 再不够就跳过)。
//     离线实测 (10 张最坏的卡 "99.9", 预算 800): 1x1 单卡 **261** 个矩形 ⇒
//     3 张就把 783 吃掉, 剩下的 17px 连一张 2x2 (88) 都放不下 ⇒
//     **后面 7 张卡一个数字都不显示** (信息全丢了, 而预算还剩着)。
//   ★ 现在分两个阶段, 仍然"每一步先问够不够", 但**先把每一张能画的卡都安排上**:
//       ① 从左到右, 每张能画的卡先占最省的 **2x2** 一档; 放不下的从**后面**跳过;
//       ② 再用剩下的预算, 从左到右把卡片**升级**成 1x1 (升级只花 n1 - n2 的差价)。
//     结果 (实测, 预算 800):  3 张卡 ⇒ 全部 1x1 (783);  4 张卡 ⇒ 3 张 1x1 + 1 张 2x2;
//       10 张最坏 ⇒ 9 张 2x2 + 1 张跳过 (792)。无论哪种, 本帧总数**永远 <= budget**。
//   ★ 为什么不按"每张卡的最坏值"预留: 那会让 10 张卡时谁也画不出 (预留本身就超预算);
//     这里用的是**这一帧真实读数**算出来的 n1/n2 ⇒ 读数短 (如 `2.4`) 的那些卡会在
//     同样的预算下自动拿到更清晰的档位。
// ---------------------------------------------------------------------------
constexpr int32_t CdAllocSteps(const int32_t *n1, const int32_t *n2, int32_t count, int32_t budget,
                               int32_t *steps_out, int32_t cap)
{
    if (n1 == nullptr || n2 == nullptr || steps_out == nullptr || count <= 0 || cap < count)
        return 0;
    int32_t used = 0;
    for (int32_t i = 0; i < count; i++)
        steps_out[i] = CDSTEP_SKIP;
    // ① 先给每张能画的卡安排最省的 2x2
    for (int32_t i = 0; i < count; i++)
    {
        if (n1[i] <= 0 || n2[i] <= 0)
            continue; // 不可画 (字模解不出来 / 闸门挡住), 不占预算
        if (used + n2[i] > budget)
            continue; // ★ 先问够不够: 放不下就跳过这张 (后面的卡仍然有机会)
        steps_out[i] = CDSTEP_BLOCK2;
        used += n2[i];
    }
    // ② 用剩下的预算从左到右升级成 1x1 逐像素
    for (int32_t i = 0; i < count; i++)
    {
        if (steps_out[i] != CDSTEP_BLOCK2)
            continue;
        const int32_t extra = n1[i] - n2[i];
        if (extra < 0 || used + extra > budget)
            continue;
        steps_out[i] = CDSTEP_BLOCK1;
        used += extra;
    }
    return used;
}

// ---------------------------------------------------------------------------
// 位置闸门 (硬规矩 ①②⑤⑥): CDSKIP_NONE = 这张卡可以画; 否则就是**跳过原因位**。
//   三条都在这里判完 —— 而且离线单测**用同一个函数**逐卡断言:
//     ① 数字与底衬外框必须**整个落在卡面内** (放不下 ⇒ PANEL, 绝不溢出卡面);
//     ② 不许与游戏自己的**阳光费用**数字相交 (相交 ⇒ COST);
//     ③ 不许与**阳光计数器**相交 (相交 ⇒ SUN, 宁可这张卡不显示)。
//   ★ v31: 阴影层已经删掉 ⇒ 闸门里**没有**阴影那一条了 (不再为不存在的东西把关)。
// ---------------------------------------------------------------------------
constexpr uint32_t CdPlaceGate(const CardRect &card, const CdTextGeom &g, int32_t bank_x, int32_t bank_y)
{
    const CardRect t = CdTextRect(g, card);
    const CardRect p = CdPanelRect(g, card);
    if (CdRectEmpty(t) || CdRectEmpty(p) || !CdRectInside(t, card) || !CdRectInside(p, card))
        return CDSKIP_BIT_PANEL;
    const CardRect cost = CdSunCostRect(card);
    if (CdRectOverlap(t, cost) || CdRectOverlap(p, cost))
        return CDSKIP_BIT_COST;
    const CardRect sun = CdSunCounterRect(bank_x, bank_y);
    if (CdRectOverlap(t, sun) || CdRectOverlap(p, sun))
        return CDSKIP_BIT_SUN;
    return CDSKIP_NONE;
}

// 单张卡闸门 (CdCardGate): CDSKIP_NONE = 这张卡要画
//   ★ 语义直接照抄 game-src/Lawn/SeedPacket.cpp:150-160 (Update) 与 Draw:
//       * mRefreshCounter 每 tick **+1**, 超过 mRefreshTime 才 Activate() ⇒ 剩余 = time - counter;
//       * 就绪 = **mActive == true** (游戏自己置的), 冷却中 = **mActive==false && mRefreshing==true**;
//       * `Deactivate()` (把卡拿在光标上) 会把 mRefreshing 清 0 ⇒ 那种状态**不显示**。
constexpr uint32_t CdCardGate(int32_t packet_type, int32_t active, int32_t refreshing, int32_t counter,
                              int32_t total)
{
    if (packet_type == kSeedTypeNone)
        return CDSKIP_BIT_EMPTY;
    if (active != 0)
        return CDSKIP_BIT_READY;
    if (refreshing == 0)
        return CDSKIP_BIT_NOT_REFRESHING;
    if (CooldownTenths(counter, total) <= 0)
        return CDSKIP_BIT_TENTHS;
    return CDSKIP_NONE;
}

