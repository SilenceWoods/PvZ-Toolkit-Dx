// 跨进程"开关"连线的健康判定 (v28 新增; 纯函数 ⇒ 离线单测直接钉住)
//
//   ★★ 硬规矩 (由 v27 的实机 bug 换来, 见文件顶部 v28 说明) ★★
//     凡是"工具界面上的勾选框"驱动"DLL 里的行为"的功能, 都必须:
//       ① 工具**每帧**把开关状态原样写进控制块 (不许与"地址自检/一次性定位"结果相与);
//       ② DLL **每帧从控制块读**同一份值 (不许注入时缓存成 static);
//       ③ DLL 把**自己实际读到的值**回写 (`cd_seen_on`), 工具把两侧状态**都显示出来**;
//       ④ 由**同一个纯函数**判"连线是否异常"并给出唯一一份结论文案。
//     为什么: 少了 ① 就会出现"勾着却是关"; 少了 ③④ 就会"看起来生效、其实什么都没做",
//     而且**没有任何地方**能看到两侧到底同步了没有 —— v27 正是这么静默失败的。
//
//   这个函数只做判断、返回一个"异常码"; 中文文案由工具侧翻译 (理由见 CdSkipBit 上面那段:
//   gen_glyphs.ps1 只扫 frontend/ + src/ + inc/, 写在本头文件里的中文不会进字形表 ⇒ 界面上
//   会变成方框)。⇒ 判断只有这一份, 文案也只有一份。
// ===========================================================================
enum CdWiringAnomaly : uint32_t
{
    CDWIRE_OK = 0,             // 两侧一致 (含"两边都是关"这种正常情况)
    CDWIRE_NEVER_SENT = 1,     // 勾着 + 有通道 + 钩子已装, 可 DLL 一次都没被调用 (帧级断线)
    CDWIRE_SEEN_OFF = 2,       // ★ v27 的病: 勾着, DLL 却读到 0 —— "开"没送到 DLL 侧
    CDWIRE_NOT_LATCHED = 4,    // 勾着 + 地址已下发, 可补丁没打上 (cd_hook_ok == 0)
    CDWIRE_NO_DRAW = 8,        // 勾着 + 两侧都是开 + 有卡在冷却, 却一张都没画出来 (卡级闸门挡住)
};

// 输入就是"两侧状态"本身, 再加三个"结果"字段。
//   tool_on        = 工具侧勾选框的真实状态 (g_cooldown_on)
//   dll_seen_on    = DLL 回读的 cd_seen_on (DLL 本帧实际读到的那份)
//   dll_calls      = DLL 钩子被调用的总帧数 (0 = 跳板一次都没跑)
//   hook_latched   = cd_hook_ok (补丁已打上; ★ 这是闩锁, 会**滞后于**地址自检)
//   addr_published = cd_call_addr != 0 (这一帧地址确实下发过)
//   drawn          = cd_cards_last (本帧真的画出来的卡数)
//   cooling        = cd_cards_cooling (本帧处于冷却中的卡数)
constexpr uint32_t CdWiringHealth(bool tool_on, uint32_t dll_seen_on, uint32_t dll_calls,
                                 uint32_t hook_latched, uint32_t addr_published, uint32_t drawn,
                                 uint32_t cooling)
{
    // 没勾: 两侧本来就该是"关", 不存在断线问题
    if (!tool_on)
        return CDWIRE_OK;

    // ---- 以下都是"工具勾着"的情况: 那么 DLL 侧**必须**也看到 1 ----
    // ★ 只有在 DLL 真的在跑 (`dll_calls > 0`) 时才敢断言"读到的是 0" ——
    //   跳板还没跑过时 cd_seen_on 仍是初值 0, 那种情况下报"不一致"是**误报**。
    if (dll_calls > 0 && dll_seen_on == 0)
        return CDWIRE_SEEN_OFF;

    // 跳板一次都没跑: 要么补丁没打上 (可解释), 要么地址/钩子不对
    if (dll_calls == 0)
    {
        if (hook_latched == 0)
            return CDWIRE_NOT_LATCHED;
        return CDWIRE_NEVER_SENT;
    }

    // 跳板在跑, 地址这一帧却没有 ⇒ 补丁随时可能因为"读不到原字节"而失效 (闩锁滞后)
    if (addr_published == 0)
        return CDWIRE_NOT_LATCHED;

    // 两侧都是开、也在真的画 (drawn > 0) ⇒ 连线完全正常, 剩下的"少画了几张"
    // 由 cd_skip_mask 解释 (那是**卡级**原因, 不是连线问题)。
    if (drawn > 0)
        return CDWIRE_OK;

    // 一张都没画: 本帧**确实有卡在冷却**却一张都没出来 —— 连线是通的 (两侧都是开),
    // 所以问题在 DLL 内部的绘制闸门, 由 CDSKIP_* 那组原因解释。
    //   ★ 反过来, 冷却中 0 张 = 本来就没东西可画, **不是**异常 (v28 修的第一版判错过这个)。
    if (cooling > 0)
        return CDWIRE_NO_DRAW;

    return CDWIRE_OK;
}

