//
//   ★★ 根因: 字模的边缘墨色是**按"变暗的卡面"标定的**, 而底下的卡面会变亮 ★★
//     ① 离线字模 (cd_font.h) 存的灰度 = `kCdFontGrayBg(64) + 覆盖度 x (255-64)/255`
//        —— 也就是"白字画在**游戏叠了 Color(64,64,64) 的暗卡面**上"的样子:
//        满覆盖 = 255 (纯白), 低覆盖 = 76..160 (**比暗卡面亮、比亮卡面暗**);
//     ② 但底下的卡面**不是恒定的 64**: 游戏画的"暗化层"是
//        `SeedPacket.cpp:525-537` 用 `Color(64,64,64)` 再色化一遍**卡面图片与种子图**
//        (`g->SetColorizeImages(true)` ⇒ **乘法**), 而且被 `ClipRect(x, y, 50, aDarknessHeight)`
//        裁成一条**会收缩的横带** (`aDarknessHeight = FloatRoundToInt(68 x aPercentDark) + 2`,
//        百分比 = 剩余/总长) ⇒ 冷却推进时, **暗化层的下沿会从卡底(70)一路往上扫过数字区 (卡顶 27..40)**;
