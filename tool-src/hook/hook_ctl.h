enum CdSkipBit : uint32_t
{
    CDSKIP_NONE = 0,
    CDSKIP_BIT_OFF = 1u << 0,            // 开关关着 (正常)
    CDSKIP_BIT_NO_ADDR = 1u << 1,        // 工具没下发 SetColor/DrawRect 地址
    CDSKIP_BIT_BOARD = 1u << 2,          // Board* 为 0 / 不可读
    CDSKIP_BIT_BANK = 1u << 3,           // Board::mSeedBank 指针不合法
    CDSKIP_BIT_UNREADABLE = 1u << 4,     // 卡数组整段不可读 (VirtualQuery 确认不了)
    CDSKIP_BIT_COUNT = 1u << 5,          // mNumPackets 不在 1..kMaxSeedPackets
    CDSKIP_BIT_EMPTY = 1u << 6,          // 空槽 (正常)
    CDSKIP_BIT_READY = 1u << 7,          // 已就绪 (正常)
    CDSKIP_BIT_NOT_REFRESHING = 1u << 8, // 既没就绪也没冷却 = 卡被拿在光标上 (正常)
    CDSKIP_BIT_TENTHS = 1u << 9,         // 冷却读数为 0/无效 (刚好走完那 1 tick)
    CDSKIP_BIT_GEOM = 1u << 10,          // 卡宽/高不合理 ⇒ 坐标算不出
    CDSKIP_BIT_PANEL = 1u << 11,         // 数字/底衬放不进卡面可画区 (含"反算出来的字太小")
    // ★ v29 新增两条: **绝不许遮阳光** (用户实机投诉"挡住了阳光数")
    CDSKIP_BIT_COST = 1u << 12,          // 会压住**卡上的阳光费用**数字 (卡面 [卡顶+54, 卡底))
    CDSKIP_BIT_SUN = 1u << 13,           // 会压住**阳光计数器** (SeedBank::Draw 末尾那个数字)
    // ★ v30 新增, v31 改语义: 本帧的**矩形预算**用完了 ⇒ 这张卡不画
    //   (宁可少一张, 也不许拖慢游戏)。v31 的降级阶梯是 1x1 逐像素 -> 2x2 聚合 -> 跳过,
    //   预算与阶梯见 kCdRectBudget 与 CdPickStep 的说明。
    CDSKIP_BIT_BUDGET = 1u << 14,        // 本帧画字的矩形数已达上限 (连 2x2 聚合都放不下)
    CDSKIP_BIT_LAST = CDSKIP_BIT_BUDGET,
};

// "正常"的位: 出现这些时状态行不该报警 (只是本帧没有需要画的卡)
constexpr uint32_t kCdSkipNormalBits =
    CDSKIP_BIT_EMPTY | CDSKIP_BIT_READY | CDSKIP_BIT_NOT_REFRESHING;

