// 冷却绘制"为什么没画"的原因位图 (DLL 写, 工具翻成人话显示)
//
//   ★ 用位图而不是单个枚举: 一帧里可能同时有"这张卡底衬放不下""那张卡读数已是 0"。
//   ★ 中文文案一律留在**工具侧** (tool-src/src/pvz.cpp): gen_glyphs.ps1 只扫
//     frontend/ + src/ + inc/, **扫不到 hook/ 里的字符串** —— 把中文写在这里,
//     界面上的字会变成方框 (踩过)。
//   ★ "正常"的位 (空槽/已就绪/卡被拿在光标上) 也在位图里, 但工具侧不报警,
//     只用来解释"本帧一张都没画"是正常的。
