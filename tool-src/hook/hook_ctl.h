// ---------------------------------------------------------------------------
// 钩点补丁: 把 `call 原目标` 换成 `call 我们的跳板`, **5 字节等长**。
//
//   ★★ 必须仍然是 **call(0xE8)**, 不能图省事写成 jmp(0xE9):
//      跳板要靠"调用者压进来的返回地址"在干完活之后 ret 回去; 换成 jmp 就没有返回地址,
//      跳板里的 ret 会去弹栈上的垃圾 -> 跳到数据上执行 -> 游戏 Access Violation
//      (P2 高级暂停那次就是这么崩的, 现场 EIP 落在栈区)。
//   ★ 这条函数放在共享头里, 是为了让工具侧的自测能直接断言它 (离线可测)。
// ---------------------------------------------------------------------------
inline void EncodeCallPatch(uint32_t site, uint32_t target, uint8_t out[5])
{
    out[0] = 0xE8;
    const int32_t rel = static_cast<int32_t>(target - (site + 5));
    const uint32_t u = static_cast<uint32_t>(rel);
    out[1] = static_cast<uint8_t>(u);
    out[2] = static_cast<uint8_t>(u >> 8);
    out[3] = static_cast<uint8_t>(u >> 16);
    out[4] = static_cast<uint8_t>(u >> 24);
}

