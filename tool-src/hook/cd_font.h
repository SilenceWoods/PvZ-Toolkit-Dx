// 字符 -> 表下标 (-1 = 表里没有这个字符)。运行期不查表也能用:
//   数字 '0'..'9' 直接是下标 0..9, '.' = 10, '-' = 11 (见 kCdFontChars 的顺序)。
constexpr int32_t CdFontIndexOf(char c)
{
    for (int32_t i = 0; i < kCdFontCharCount; i++)
        if (kCdFontChars[i] == c)
            return i;
    return -1;
}

