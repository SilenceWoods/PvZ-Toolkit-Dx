// ---------------------------------------------------------------------------
// cd_font.h -- 卡片冷却数字的**离线灰度字模表** (逐像素 8 位灰度)
//
//   ★★ 这个文件是**生成的**, 不要手改 ★★
//     生成器: env/scripts/gen_cd_font.py
//     字体:   tahoma.ttf  (像素字号 19, 基线 14)
//     命令:   python env/scripts/gen_cd_font.py --font C:/Windows/Fonts/tahoma.ttf
//     生成日: 2026-10-11
//
//   为什么不用游戏自带的字体 API (TodDrawString): 它要在栈上构造 SexyString
//   (= 本工程的 std::string), 而本 DLL 是 -nostdlib + 自备极简 CRT、**没有
//   operator new** => 堆操作 = Access Violation / 堆损坏 = 崩游戏。
//   所以字形在**离线**光栅化, 出厂只带这张表; 运行期只用已验证的
//   Graphics::SetColor + Graphics::FillRect 把每个像素画成一个矩形。
//
//   表结构: 每个字符一块 CANVAS_W x CANVAS_H 的**逐像素 8 位灰度**画布
//   (行主序, 0 = 透明不画)。这个灰度是**覆盖度的记录**, 不是最终颜色:
//     灰度 = 64 + 覆盖度 x (255 - 64) / 255
//   其中 64 就是游戏自己给冷却中的卡面叠的暗色 (SeedPacket.cpp:529 的
//   `aPlantG.SetColor(Color(64, 64, 64, 255))`) —— 于是「白字渐渐融进变暗的卡面」
//   就是这套数值的物理含义。
//
//   ★★ v36 (2026-10-12) 这个灰度**怎么用**: 反解出覆盖度, 画成「白字 + A = 覆盖度」★★
//     运行期 (hook_ctl.h 的 `CdGlyphCoverage()` / `CdGlyphInk()`) 做两件事:
//       ① 覆盖度 = (灰度 - 64) x 255 / (255 - 64)  (本文件 quantise() 的反函数)
//          —— 灰度 == 0 ⇒ 覆盖度 0 (不画); 灰度 > 0 ⇒ 覆盖度 **>= 1** (绝不会变成全透明);
//       ② 画出来的颜色 = **白 (255,255,255) + A = 覆盖度** (默认), 或者
//          **不透明灰 max(灰度, 160) + A = 255** (回退: 环境变量 PZTK_CD_NOALPHA=1)。
//     ⇒ 游戏按 SRCALPHA/INVSRCALPHA 把它叠在**任何**卡面上:
//          输出 = 卡面 + (255 - 卡面) x A / 255
//        ① 永远不比卡面更暗 ⇒ **不可能出现黑点**;
//        ② A 只在覆盖度 == 0 时才是 0 ⇒ **有墨必有画, 不可能出现空洞**;
//        ③ A 与覆盖率成正比 ⇒ 抗锯齿梯度完整保留 (暗卡面 58~62 上它与本表的
//           定标值只差 <= 2 级 ⇒ 观感就是 v31 那一版, 而那一版用户是接受的)。
//
//   ★★ v35 (2026-10-12) 那一版为什么被推翻 (留档, 别再改回去) ★★
//     v35 用「不透明灰 + 抬到下限 160 + 丢掉比 32 更淡的块」:
//       ① 「丢掉比 32 更淡的块」= 一条**低于某灰度就跳过不画**的路径 —— 天生的挖洞
//          路径。它当时恰好没丢现有字模 (表里最暗 = 76 > 32), 纯属**运气**;
//       ② 「抬到 160」把 76..159 这 **217 个像素 (占 747 的 29%)** 全压成同一个灰度
//          ⇒ 抗锯齿没了, 而且结果**完全押在「卡面 <= 128」这个推算值上**。
//     用户实机看到的就是这个的后果 —— 原话: 那些东西**不是黑点, 是「洞」**
//     (字形被挖空 / 笔画断成规则缺口), 因为卡面对 160 的那一片像素正好与底色同值。
//     ⇒ v36: 上面的 ① 整条删除 (`kCdFontInkMinCover = 0` + `static_assert` +
//       recttest 的「已画 ⊇ 墨迹」断言), ② 只留在不透明回退路径里。
//     ★ 本表的数值**一个字节都没变**: 它仍然是「覆盖率 → 该写多少灰度」的唯一记录。
//
//   ★★ v31 为什么不再用「同灰度水平行程 (run-length)」来省矩形 ★★
//      v30 把每行的同灰度像素并成一根 1px 高的行程, 但 7x9 的画布上抗锯齿只有
//      7 级、笔画几乎全是满覆盖 ⇒ 每个字形看起来就是**方块**; 再叠一层右下偏移
//      1px 的暗色 (kCdFontShadowGray=8) ⇒ 白块外面一圈**粗黑边**
//      (用户实机原话: 「这种方块数字不太好看」)。v31 = 逐像素灰度 + 10x14 画布,
//      并把阴影整层**删掉** (字本来就画在变暗的卡面上, 不需要描边)。
//
//   规模: 12 个字符 / 747 个墨迹像素 / 1680 字节数据 (整个画布都存下来)。
// ---------------------------------------------------------------------------

